#!/usr/bin/env python3
"""Каналы голоса: две линии ОДНОГО участника, а не два участника.

Зачем. С 2026-08-26 у Кими в `~/.kimi-code/config.toml` два ключа —
`providers.moonshotai` (алиас `moonshotai/kimi-k3`) и `providers.moonshotai2`
(алиас `moonshotai2/kimi-k3`), и принадлежат они РАЗНЫМ организациям.
Проверено живым замером, а не выведено из документации: два одновременных
HTTP-вызова прошли параллельно (18.7 с каждый, оба 200, ни одного 429), и
два CLI, запущенные разом из разных каталогов, ответили «Лима» и «Сантьяго»
за 10 и 12 секунд. Значит потолок `concurrency = 1` висит на ОРГАНИЗАЦИИ, и
второй ключ обходит его по-настоящему.

ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Второй ключ — не второй голос стола. Наказ Автора
(2026-08-26): Кими остаётся ОДНИМ участником. Иначе Moonshot получает два
места в карте покрытия, счёт перекоса (правило 7) начинает врать в его
пользу, а «двое согласились» окажется одной моделью, ответившей дважды.
Отсюда всё устройство модуля: канал — свойство ТРАНСПОРТА. Имя в ленте
одно (`kimi`), адрес `@kimi` один, в статистике строка одна; разной
бывает только линия, которой ушёл вызов, и она называется вслух полем
`channel` в журнале.

Ключей здесь НЕТ и быть не должно. В коде живёт только ИМЯ модели —
алиас, по которому CLI сам находит ключ в своём конфиге. Мы этот конфиг
читаем, но исключительно ради двух вещей: подтвердить, что алиас
объявлен, и узнать имя провайдера за ним.

ПОЧЕМУ КАНАЛ ПОДТВЕРЖДАЕТСЯ КОНФИГОМ. Правило 8.5: свойство, объявленное
полем в журнале, обязано быть обеспечено механикой, иначе поле врёт.
Запись `channel: "alt"` означает «ушло вторым ключом» — и если второго
ключа на машине нет, канала нет тоже: список схлопывается до одного, и
код ведёт себя ровно как до правки. Признака организации в конфиге нет
(различаются только два разных `api_key`), поэтому «разные организации» —
не объявление, а наблюдение; в коде оно держится на имени провайдера,
которое и становится именем ворот.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

KIMI_CONFIG = Path.home() / ".kimi-code" / "config.toml"

# Каналы Кими, от основного к запасному. Порядок значим: первый —
# основной, он берётся всегда, когда свободен.
#
# `dir` — рабочий каталог голоса в live.py, и он у каналов ОБЯЗАН быть
# разным. У Кими нить привязана к cwd: `-c` продолжает «предыдущую
# сессию ЭТОГО рабочего каталога», а указателя на неё нет — CLI выбирает
# последнюю сессию каталога по времени. Два канала из одного каталога
# подхватят нить друг друга, и получится ровно то, о чём предупреждает
# комментарий в live.py: в ленте две реплики, а на диске две РАЗНЫЕ
# сессии по одной реплике в каждой. Плюс `state.json` (нить, курсор,
# счётчик ходов) лежит в каталоге голоса и пишется без блокировки —
# два пишущих процесса просто затрут друг друга.
#
# С 2026-09-23 (наказ Автора: «Кими пересел на CLI») первая линия —
# ПОДПИСКА Kimi Code: провайдер `managed:kimi-code` (вход `kimi login`,
# токен в ~/.kimi-code/credentials/kimi-code.json), алиас `kimi-code/k3`,
# адрес api.kimi.com/coding/v1. Ключевые линии (`moonshotai*`) остаются
# РЕЗЕРВОМ на случай быстрого исчерпания квоты плана (5-часовое окно и
# месячный лимит — по документации Kimi Code); резерв включает галочка
# окна (`CHOIR_KIMI_RESERVE`, умолчание — включён). Роль линии —
# поле `role`: plan | api; в журнал уходит имя линии (`channel`) и
# модель, как раньше.
_KIMI = (
    {"name": "code", "model": "kimi-code/k3",      "dir": "kimi-code", "role": "plan"},
    {"name": "main", "model": "moonshotai/kimi-k3",  "dir": "kimi",      "role": "api"},
    {"name": "alt",  "model": "moonshotai2/kimi-k3", "dir": "kimi-alt",  "role": "api"},
)
PLAN_MODEL = _KIMI[0]["model"]


def reserve_on(env: dict | None = None) -> bool:
    """Галочка «резерв по ключам API»: CHOIR_KIMI_RESERVE=0 выключает.
    Умолчание — включён: резерв и заведён ради «квота плана кончилась,
    а стол идёт»."""
    env = os.environ if env is None else env
    return str(env.get("CHOIR_KIMI_RESERVE", "1")).strip().lower() not in ("0", "false", "off", "")


def gate_name(provider: str) -> str:
    """Имя ворот = ОРГАНИЗАЦИЯ (провайдер), а не имя голоса.

    Ворота `kimi.lock` держали очередь всем вызовам Кими сразу — с двумя
    ключами это заперло бы второй канал в чужой очереди, и выигрыш
    исчез бы молча: в журнале это выглядело бы как «Кими опять долго
    думает», то есть ровно та ложь, ради которой заведено поле
    `queued_s`. Очередь принадлежит тому, кто её накладывает, —
    организации за ключом. Если завтра ещё один голос пойдёт тем же
    ключом, он встанет в те же ворота сам, без правки кода.
    """
    return re.sub(r"[^A-Za-z0-9_.-]", "_", provider) or "unknown"


def _models_from_config(path: Path) -> dict[str, str] | None:
    """{алиас модели: провайдер} из конфига CLI. `None` — конфиг не прочитан.

    Ключи (`api_key`) не читаются и не возвращаются: коду они не нужны,
    их дело — лежать в конфиге, куда смотрит сам CLI.
    """
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError:
        return None
    try:
        import tomllib                      # stdlib с 3.11
        data = tomllib.loads(raw)
        models = data.get("models") or {}
        if isinstance(models, dict):
            return {k: str(v.get("provider") or k.split("/")[0])
                    for k, v in models.items() if isinstance(v, dict)}
    except Exception:                                          # noqa: BLE001
        pass
    # Запасной разбор: tomllib нет (Python < 3.11) или конфиг не разобрался.
    # Заголовков `[models."<алиас>"]` достаточно — провайдера тогда берём
    # из префикса алиаса. Падать здесь нельзя: неразобранный конфиг не
    # повод оставить стол без Кими вообще.
    found = re.findall(r'^\[models\."([^"]+)"\]', raw, re.M)
    return {a: a.split("/")[0] for a in found} if found else {}


def kimi_channels(path: Path = KIMI_CONFIG) -> tuple[dict, ...]:
    """Каналы Кими, ПОДТВЕРЖДЁННЫЕ конфигом.

    Не нашли конфиг (или в нём нет наших алиасов) — возвращаем один
    основной канал: код обязан вести себя как до правки, а не выдумывать
    линию, которой на машине нет.
    """
    # `or {}`: НЕПРОЧИТАННЫЙ конфиг — это неподтверждение, а не разрешение.
    # Раньше `if declared and …` при None/{} выключало проверку целиком, и
    # запасная линия объявлялась даже там, где её нет: конфиг лежит по
    # другому пути, не распарсился, старый Python — и каждый второй вызов
    # уходил бы на `-m moonshotai2/kimi-k3`, CLI падал бы на неизвестной
    # модели, а в журнал легло бы `error` ПОД ИМЕНЕМ ГОЛОСА с полем
    # channel: "alt" — отказ инфраструктуры как свойство участника
    # (правила 4 и 8.5). Проверено ревьюером: MISSING/EMPTY/BROKEN конфиг
    # давали main+alt, хотя докстрока обещает обратное.
    declared = _models_from_config(path) or {}
    out: list[dict] = []
    for c in _KIMI:
        if c["model"] not in declared:
            continue
        prov = declared.get(c["model"]) or c["model"].split("/")[0]
        out.append(dict(c, provider=prov, gate=gate_name(prov)))
    plan = [c for c in out if c.get("role") == "plan"]
    if plan and not reserve_on():
        # Подписка есть, резерв выключен галочкой: ключевые линии не
        # зовутся вовсе — иначе «резерв выключен» было бы полем без
        # механики (правило 8.5), а баланс списывался бы молча.
        out = plan
    if not out:
        # Ни подписки, ни ключей в конфиге: ведём себя как до правки —
        # одна ключевая линия по умолчанию CLI (не подписка: её без
        # входа нет, и «code» в журнале врало бы про транспорт).
        c = _KIMI[1]
        prov = c["model"].split("/")[0]
        out = [dict(c, provider=prov, gate=gate_name(prov))]
    return tuple(out)


_WARNED: set[str] = set()


def resolve_alias(c: dict, want: str, path: Path = KIMI_CONFIG, warn=None) -> str:
    """Алиас `-m` для линии с учётом модели, заданной окном (без
    провайдера: провайдер — у линии, он выбирает ключ/подписку).

    Принимается только ОБЪЯВЛЕННЫЙ в конфиге CLI алиас: у подписки
    свои имена (k3, k3-256k, kimi-for-coding…), у ключей — свои
    (kimi-k3); склейка «префикс линии + модель окна» без проверки
    роняла бы ход «неизвестной моделью» под именем голоса — ровно на
    резерве, ради которого линия заведена (ревизия 23.09: субагент,
    grok, deepseek). Конфиг не прочитан: подписка — своя модель линии,
    ключевая линия — склейка, как до правки."""
    if not want:
        return c["model"]
    want = want.split("/")[-1]
    alias = c["model"].split("/")[0] + "/" + want
    declared = _models_from_config(path) or {}
    if alias in declared or (not declared and c.get("role") != "plan"):
        return alias
    if warn and alias not in _WARNED:
        _WARNED.add(alias)
        warn(f"⚠ kimi: алиас {alias} не объявлен в {path.name} — линия "
             f"{c['name']} идёт своей моделью {c['model']}")
    return c["model"]


def gates_for_model(chans: tuple[dict, ...], model_alias: str) -> list[str]:
    """Ворота линий, чей провайдер стоит в алиасе `-m` (кресло и
    ревизия зовут Кими ОДНИМ алиасом — замок обязан быть той же
    организации/подписки, иначе кресло берёт свободный ключевой замок и
    всё равно бьёт в занятую подписку; ревизия 23.09: grok, субагент).
    Нет совпадений — все ворота (как раньше)."""
    pref = (model_alias or "").split("/")[0]
    out = sorted({c["gate"] for c in chans if c["model"].split("/")[0] == pref})
    return out or sorted({c["gate"] for c in chans})


def plan_line(chans: tuple[dict, ...]) -> dict | None:
    """Линия подписки среди каналов голоса (None — подписки нет)."""
    return next((c for c in chans if c.get("role") == "plan"), None)


def by_gate(chans: tuple[dict, ...], gate: str | None) -> dict | None:
    """Канал, которому принадлежат занятые ворота (их вернул first_free_gate)."""
    return next((c for c in chans if c["gate"] == gate), None)


def describe(chans: tuple[dict, ...]) -> str:
    """Строка для `voices`/`who`: что за линии есть у голоса."""
    return " · ".join(f"{c['name']}={c['model']} (ворота {c['gate']})"
                      for c in chans)


if __name__ == "__main__":                                     # быстрый осмотр
    for c in kimi_channels():
        print(c)
