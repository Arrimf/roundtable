def cmd_ask(a) -> int:
    """Новая тема — слепым первым ходом (решение стола от 2026-08-14)."""
    names = a.voices.split(",") if a.voices else roster()
    post(HUMAN, "topic", a.text, topic=a.topic or "")

    # С досье контролёр в слепую фазу не идёт: его такт — второй, и
    # сверять он должен уже сказанное, а не отвечать наравне.
    speaking = [n for n in names if not (DOSSIER and n == AUDITOR)]
    print(f"тема: {a.text}\nслепой первый ход: {', '.join(speaking)}\n")
    evs = deliver(speaking, blind=True)

    if DOSSIER and AUDITOR:
        print(f"\nтакт сверки: {AUDITOR} проверяет факты по живым файлам\n")
        ev = audit(AUDITOR, a.text, evs)
        mark = {"verdict": "⚖", "pass": "○"}.get(ev["kind"], "✗")
        print(f"{mark} {AUDITOR:<8} {ev.get('elapsed_s', 0):>6.1f} с  "
              f"{len(ev.get('text', '')):>5} симв."
              f"{'' if ev['kind'] != 'error' else '  ' + ev.get('detail', '')[:70]}")
        evs.append(post(**ev))

    note = coverage(names, evs)
    post("choir", "note", note)
    print(f"\nслепая фаза закрыта — ответы в ленте, дальше разговор живой\n{note}")
    return 0


def hand_word(src_ev: dict, names: list[str], why: str,
              pool: list[str]) -> list[dict]:
    """Дать слово — с ПЕРЕДАЧЕЙ следующему, если все позванные выпали.

    Две починки одного инцидента (2026-08-25, вопрос про GitHub, 10 минут
    пустой ленты):

    1. Кого позвали — говорится В ЛЕНТУ, а не только в stdout. Строка
       «вступают …» шла в лог акта, который Автор не видит; он смотрел в
       пустую комнату, не зная, кого ждёт и сколько.
    2. Если ход провалился ЦЕЛИКОМ (все позванные — error), слово
       передаётся следующему по тишине из pool, а не умирает: раньше
       цикл разговора видел последним событием error и молча выходил —
       ошибка канала останавливала стол, хотя за столом ещё пятеро.

    pool — кем можно заменить выпавшего. Для «быстрого вопроса» (--once)
    и для адресного «@имя» сюда передаются сами names: подпись кнопки
    обещает один канал, а адрес — выбор человека; молча оплатить вместо
    названного другого было бы обманом (адресный случай нашёл субагент:
    «спросили @gemini — заплатили за ответ другого»). Провал честно
    объявляется, и слово возвращается человеку.

    Потолок передач — MAX_HANDOFFS. Без него один вопрос при мёртвых
    каналах оплачивал перебор ВСЕГО стола: замер субагента — 10 вызовов
    (9 впустую) при одном живом голосе из шести, до 31 в худшей
    комбинации. Три канала подряд легли — дело не в каналах: комната
    говорит об этом и ждёт человека.
    """
    tried: set[str] = set()
    handoffs = 0
    note = f"слово → {', '.join(names)} ({why})"
    while True:
        # word_to — структурное поле для окна: индикатор «кто думает»
        # раньше крутился у ВСЕХ шести, хотя вызван был один (наказ
        # Автора 2026-08-25). act — идентификатор акта окна (кладёт
        # spawn через RT_ACT_ID): без него заметки двух параллельных
        # действий склеивались в один глобальный список (нашли codex и
        # grok). Текст заметки — человеку, поля — машине.
        post("choir", "note", note, word_to=list(names),
             act=os.environ.get("RT_ACT_ID", ""))
        print(f"вступают ({why}): {', '.join(names)}\n")
        res = deliver(names)
        tried |= set(names)
        if any(e.get("kind") in ("say", "pass", "verdict") for e in res):
            return res
        fell = "; ".join(f"{e['author']}: {(e.get('detail') or 'сбой')[:60]}"
                         for e in res) or "ответов нет"
        rest = [v for v in pool
                if v not in tried and v != src_ev.get("author")]
        if not rest or handoffs >= MAX_HANDOFFS:
            reason = ("кандидатов больше нет" if not rest else
                      f"потолок передач ({MAX_HANDOFFS}) исчерпан")
            post("choir", "note",
                 f"ход не состоялся: {fell}. {reason} — слово "
                 f"возвращается человеку", word_to=[],
                 act=os.environ.get("RT_ACT_ID", ""))
            print(f"ход не состоялся: {fell} ({reason})")
            return res
        handoffs += 1
        names = _quietest(rest)[:1]
        why = "передача после сбоя"
        note = f"{fell} — слово передаётся: {names[0]}"


def cmd_say(a) -> int:
    ev = post(HUMAN, "say", a.text)
    allowed = a.voices.split(",") if a.voices else roster()
    names, why = pick_voices(ev, allowed)
    if not names:
        print("никто не вступает")
        return 0
    once = bool(getattr(a, "once", False))
    # Адрес — выбор человека: подменять адресата передачей нельзя,
    # как и в --once (нашёл субагент). pool = сами names.
    res = hand_word(ev, names, why,
                    names if (once or why == "по адресу") else allowed)

    if once:
        # ОДИН ХОД И ВСЁ. Ради «быстрого вопроса» из окна: его подпись
        # обещает «зовётся ОДИН канал, дёшево именно поэтому», а `say`
        # после первого ответа продолжал разговор по ВСЕМУ составу
        # (pick_voices(last, roster()) ниже игнорирует --voices) —
        # платными вызовами, пока не упрётся в guards. Подпись обещала
        # одно, механика делала другое: правило 8.5 в чистом виде.
        # Нашли grok и kimi независимо, ревьюя диф окна.
        print("\n(--once: разговор дальше не продолжается)")
        return 0

    # Разговор продолжается сам, пока не упрётся в предел или в тишину.
    while True:
        stop = guards(roster())
        if stop:
            post("choir", "note", stop)
            print(f"\n⏸  {stop}")
            break
        note = skew_note(roster())
        if note:
            post("choir", "note", note)
            print(f"\n⚠  {note}")
        # Продолжение решается по РЕЗУЛЬТАТУ СВОЕГО хода, а не по хвосту
        # общей ленты. Хвост подводил дважды: заметка или act_status,
        # легшие последними, молча обрывали цикл; а после «@claude
        # @gemini» ответ Клода перекрывался более поздней ошибкой
        # Джемини — и стол замолкал, имея прозвучавший ответ (нашёл
        # grok). Свой res этих ловушек не видит.
        says = [e for e in res if e.get("kind") == "say"]
        if not says:
            break                # наш ход реплики не дал — слово у человека
        last = says[-1]
        # Чужое разговорное событие НОВЕЕ наших — параллельный процесс
        # (второе окно, слепой ход с его topic) уже ведёт стол. Уступаем:
        # два дирижёра на одной ленте продолжали чужие реплики и
        # раздваивали разговор (нашли codex и субагент).
        my_top = max((e.get("id", 0) for e in res), default=0)
        conv = [e for e in read_events() if e["kind"] in
                ("say", "pass", "error", "verdict", "topic")]
        if conv and conv[-1].get("id", 0) > my_top:
            print("в ленте параллельный разговор — этот процесс уступает")
            break
        names, why = pick_voices(last, roster())
        names = [n for n in names if n != last["author"]]
        if not names:
            break
        res = hand_word(last, names, why,
                        names if why == "по адресу" else roster())
    return 0


def cmd_tail(a) -> int:
    """Читать ленту потоком. Единственное место, где комнату видно живой."""
    seen = 0 if a.all else max(0, next_id() - 1 - a.n)
    print(f"— лента {LIVE.name} (Ctrl-C чтобы выйти) —\n")
    try:
        while True:
            for e in read_events(since=seen):
                seen = e["id"]
                who = e["author"]
                if e["kind"] == "pass":
                    print(f"[{_short(e['ts'])}] {who}: ○ ПАС")
                elif e["kind"] == "error":
                    print(f"[{_short(e['ts'])}] {who}: ✗ {e.get('detail', '')[:100]}")
                elif e["kind"] == "verdict":
                    print(f"[{_short(e['ts'])}] ⚖ {who} — СВЕРКА ПО ФАЙЛАМ:\n"
                          f"{e['text']}\n")
                elif e["kind"] == "note":
                    print(f"[{_short(e['ts'])}] — {e['text']}")
                elif e["kind"] == "topic":
                    print(f"\n═══ ТЕМА: {e['text']}\n")
                else:
                    print(f"[{_short(e['ts'])}] {who}:\n{e['text']}\n")
            if not a.follow:
                return 0
            time.sleep(1.5)
    except KeyboardInterrupt:
        return 0


def cmd_stats(a) -> int:
    ev = [e for e in read_events() if e["kind"] in ("say", "pass", "error")]
    if not ev:
        print("лента пуста")
        return 0
    counts: dict[str, dict] = {}
    for e in ev:
        c = counts.setdefault(e["author"], {"say": 0, "pass": 0, "error": 0,
                                            "chars": 0})
        c[e["kind"]] = c.get(e["kind"], 0) + 1
        c["chars"] += len(e.get("text", ""))
    total = sum(c["say"] for c in counts.values()) or 1
    print(f"{'автор':<10}{'реплик':>8}{'ПАС':>6}{'сбоев':>7}{'символов':>10}{'доля':>7}")
    for k, c in sorted(counts.items(), key=lambda kv: -kv[1]["say"]):
        print(f"{k:<10}{c['say']:>8}{c['pass']:>6}{c['error']:>7}"
              f"{c['chars']:>10}{c['say'] / total:>7.0%}")
    note = skew_note(roster())
    if note:
        print(f"\n⚠  {note}")
    return 0


def cmd_who(a) -> int:
    print(f"{'голос':<10}{'на связи':<10}{'нить':<40}{'ходов':>6}{'курсор':>8}")
    for v in VOICES:
        # У голоса с линиями строка на КАЖДУЮ: нити разные, и сводить их
        # в одну строку значит прятать, что запасная отстала.
        for ch in (channels_of(v) or (None,)):
            st = load_state(v, ch)
            s = str(st.get("session") or ("по каталогу"
                                          if VOICES[v].get("cwd_session")
                                          else "—"))
            label = f"{v}/{ch['name']}" if ch else v
            print(f"{label:<10}{'да' if available(v) else 'нет':<10}"
                  f"{s[:38]:<40}"
                  f"{st.get('turns', 0):>6}{st.get('cursor', 0):>8}")
    return 0


def cmd_reset(a) -> int:
    """Забыть нити. Лента НЕ трогается — она первоисточник и только
    дописывается; сбрасывается лишь память голосов о ней."""
    for v in VOICES:
        for ch in (channels_of(v) or (None,)):
            save_state(v, {"session": None, "cursor": next_id() - 1,
                           "turns": 0}, ch)
    post("choir", "note", "нити сброшены: голоса начинают разговор заново")
    print("нити сброшены, лента сохранена")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Choir Live — живая комната")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("ask", help="новая тема слепым первым ходом")
    p.add_argument("text")
    p.add_argument("--topic", default="")
    p.add_argument("--voices", help="через запятую; по умолчанию все")
    p.set_defaults(fn=cmd_ask)

    p = sub.add_parser("say", help="реплика в разговор")
    p.add_argument("text")
    p.add_argument("--voices")
    p.add_argument("--once", action="store_true",
                   help="один ход: вступают только названные голоса, "
                        "разговор дальше сам не идёт (для «быстрого "
                        "вопроса» из окна)")
    p.set_defaults(fn=cmd_say)

    p = sub.add_parser("tail", help="читать ленту")
    p.add_argument("-n", type=int, default=10)
    p.add_argument("--all", action="store_true")
    p.add_argument("-f", "--follow", action="store_true")
    p.set_defaults(fn=cmd_tail)

    p = sub.add_parser("stats", help="перекос по авторам")
    p.set_defaults(fn=cmd_stats)

    p = sub.add_parser("who", help="состояние нитей")
    p.set_defaults(fn=cmd_who)

    p = sub.add_parser("reset", help="сбросить нити, оставив ленту")
    p.set_defaults(fn=cmd_reset)

    for p_ in (sub.choices["ask"], sub.choices["say"]):
        p_.add_argument("--project", help="каталог обсуждаемого проекта: "
                                          "голоса получат его на чтение")
        p_.add_argument("--dossier", help="пак от dossier.py: уходит всем, "
                                          "кроме контролёра (правило 14.5)")

    a = ap.parse_args()
    global PROJECT, DOSSIER, AUDITOR
    if getattr(a, "project", None):
        PROJECT = Path(a.project).resolve()
        if not PROJECT.is_dir():
            print(f"нет такого каталога: {PROJECT}", file=sys.stderr)
            return 2
    if getattr(a, "dossier", None):
        DOSSIER = Path(a.dossier).resolve()
        if not DOSSIER.is_file():
            print(f"нет такого досье: {DOSSIER}", file=sys.stderr)
            return 2
        if not PROJECT:
            # Контролёру нужен доступ к живым файлам — иначе правило 14.5
            # исполняется на бумаге: «контролёр» без первоисточника
            # проверяет пак паком.
            print("с --dossier обязателен --project: контролёру нужны "
                  "живые файлы, иначе сверять не с чем", file=sys.stderr)
            return 2
        names = (a.voices.split(",") if getattr(a, "voices", None)
                 else roster())
        AUDITOR, why = pick_auditor(names)
        print(f"контролёр на первоисточнике: {AUDITOR or '—'} ({why})")
        print(f"досье: {DOSSIER.name}, {DOSSIER.stat().st_size / 1024:.1f} КБ "
              f"— уходит остальным\n")
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
