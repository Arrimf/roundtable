def audit(auditor: str, question: str, evs: list[dict]) -> dict:
    """Такт сверки: контролёр проверяет чужие факты по живым файлам.

    Раньше контролёр просто отвечал на общий вопрос наравне со всеми, и
    подмену в паке поймал Грок — по случайности: пак оказался обрезан, ему
    не хватило данных, и он пошёл на диск сам. Ловля ошибки, зависящая от
    того, хватило ли кому-то данных и любопытства, — это не механика, а
    везение. Здесь сверка становится работой, которую заказали.
    """
    replies = "\n\n".join(
        f"### Голос {e['author']}\n{e['text']}"
        for e in evs if e["kind"] == "say" and e["author"] != auditor)
    if not replies:
        return {"author": auditor, "kind": "error", "text": "",
                "detail": "нечего сверять: реплик не было"}
    body = AUDIT_PROMPT.format(question=question, replies=replies)

    def _make(st):
        if st.get("turns"):
            return body
        # Первый ход в ЭТОЙ нити: устав и адрес проекта иначе не дойдут —
        # audit строит промпт сам, минуя build_prompt. У голоса с линиями
        # нить своя у каждой, поэтому и решение «первый ли ход» — тоже:
        # запасная линия может быть чистой, когда основная давно в
        # разговоре.
        head = CHARTER + f"\nВаше имя за столом: {auditor}.\n"
        if PROJECT:
            head += (f"Проект открыт вам на чтение: {PROJECT}. "
                     f"Смотрите файлы сами.\n")
        return head + "\n" + body

    ev = turn(auditor, per_channel(auditor, _make))
    if ev["kind"] == "say":
        ev["kind"] = "verdict"
    ev["eyes"] = "files"
    return ev


def pick_auditor(names: list[str]) -> tuple[str | None, str]:
    """Кто в этом ходе смотрит на живые файлы вместо пака.

    Джемини кандидатом быть не может: он файлов не видит вовсе, и
    «контролёр», сверяющий пересказ с тем же пересказом, — это не сверка,
    а её имитация. Выбирает жребий: назначать контролёра значит решать,
    чью версию мира стол проверяет.
    """
    cands = [n for n in names if not VOICES[n].get("no_files")]
    if not cands:
        return None, "некого назначить: ни один вызванный голос не видит файлов"
    try:
        b = beacon()
        return drand_order(cands, b["signature"])[0], \
            f"жребий drand, round {b['round']}"
    except Exception as e:                             # noqa: BLE001
        # Здесь fail-open с явной пометкой: без контролёра ход хуже, чем
        # с невыбранным жребием контролёром. Но молчать об этом нельзя.
        return cands[0], (f"маяк недоступен ({type(e).__name__}) — взят "
                          f"первый по списку, ЖРЕБИЯ НЕ БЫЛО")


def coverage(called: list[str], evs: list[dict]) -> str:
    """Карта покрытия: кто высказался, кто пасовал, кого не звали.

    Единственная правка, которую стол потребовал единогласно на первом же
    живом прогоне (2026-08-17). Четверо из пяти независимо назвали один и
    тот же отложенный изъян: ПАС и невызов тихо читаются как «возражений
    нет». Кодекс дал точную формулировку — итог обязан звучать как
    «возражений нет СРЕДИ ОТВЕТИВШИХ», а не «возражений нет»; Грок назвал
    это consensus by absenteeism, Кими — «молчание стола это данные, а не
    отсутствие данных», Джемини предложил различать виды молчания меткой.

    Право промолчать при этом не тронуто: комната не заставляет говорить,
    она лишь перестаёт выдавать неявку за согласие.
    """
    said = [e["author"] for e in evs if e["kind"] == "say"]
    verdicts = [e["author"] for e in evs if e["kind"] == "verdict"]
    passed = [(e["author"], e.get("mark", "")) for e in evs if e["kind"] == "pass"]
    failed = [e["author"] for e in evs if e["kind"] == "error"]
    silent = [v for v in roster() if v not in called]
    bits = [f"высказались: {', '.join(said) or '—'}"]
    if DOSSIER:
        bits.insert(0, f"зрение: {AUDITOR or '—'} по живым файлам, "
                       f"остальные по досье")
    if verdicts:
        bits.append(f"сверял факты: {', '.join(verdicts)}")
    if passed:
        bits.append("ПАС: " + ", ".join(
            f"{a}{' [' + m + ']' if m else ''}" for a, m in passed))
    if failed:
        bits.append(f"выпали: {', '.join(failed)}")
    if silent:
        bits.append(f"не звались: {', '.join(silent)}")
    return "возражений нет среди ответивших — " + "; ".join(bits)


def pick_voices(ev: dict, roster: list[str]) -> tuple[list[str], str]:
    """Кого звать на эту реплику. Возвращает (голоса, объяснение).

    Порядок намеренно такой:
      1) адресное @имя — отвечает тот, к кому обратились;
      2) поднявшие руку — они уже заявили, что им есть что сказать;
      3) иначе дирижёр берёт того, кто дольше всех молчал.

    Почему НЕ опрашивать всех «есть ли что сказать»: такой опрос стоит
    почти как сам ответ (решение 3 из ЗАМЫСЕЛ.md), то есть молчание
    оплачивалось бы как речь. Дешевле решить без опроса — и признать
    честно, что это решение дирижёра, а не воля стола (правило 10).
    """
    text = ev.get("text", "")
    named = [m.lower() for m in ADDRESS_RE.findall(text)]
    addressed = [v for v in roster if v in named]
    if addressed:
        return addressed[:MAX_VOICES_PER_EVENT], "по адресу"

    # Кто говорил только что — остывает, пока есть не сказавшие ни слова
    # или молчащие дольше. Фильтр применяется и к поднявшим руку: рука
    # даёт очередь, но не право говорить без перерыва.
    events = read_events()
    # ПАС — тоже ход: голоса вызывали, он ответил, и деньги потрачены.
    # Не считать его — значит звать одного и того же бесконечно (ловилось
    # ровно так: три вызова подряд ушли Клоду, дважды получив ПАС).
    spoke = ("say", "pass", "verdict")
    # Для остывания ошибка — тоже ход: голос вызвали, время и деньги
    # потрачены. Иначе упавший канал никогда не «говорил», значит вечно
    # самый молчаливый — и жребий тишины раз за разом выбирает именно
    # сломанный канал. Ровно так комната выбрала падающего весь день
    # gemini и промолчала 10 минут (2026-08-25). Это расширение того же
    # довода, каким ПАС признан ходом (правило 7.5).
    active = spoke + ("error",)
    # Срез — ПОСЛЕ фильтра. Хвост сырой ленты теперь разбавлен
    # служебным (заметки «слово → …», act_status окна), и окно из
    # COOLDOWN сырых событий держало то одного говорившего, то ноль:
    # только что отвечавший голос «вымывался» и звался снова (нашли
    # deepseek, grok, kimi и субагент независимо — чаще всех прочих).
    conv_tail = [e for e in events if e["kind"] in active]
    recent = {e["author"] for e in conv_tail[-COOLDOWN:]}
    cool = [v for v in roster if v not in recent]

    # Рука ГАСНЕТ, когда слово дали: она означает «хочу сказать
    # следующим», а не постоянный пропуск в очередь. Иначе один раз
    # поднятая рука делает голос вечным кандидатом.
    hands = []
    for v in roster:
        h = max((e["id"] for e in events
                 if e["author"] == v and e.get("hand")), default=0)
        # active, не spoke: рука гаснет по факту ВЫЗОВА. Иначе голос,
        # поднявший руку и умерший каналом, оставался «с рукой» навсегда
        # и втягивал платный вызов в начале каждого хода — тот же дефект
        # инцидента через другую дверь (нашли codex, grok, kimi,
        # субагент; комментарий выше обещает «рука гаснет, когда слово
        # дали» — слово давали, рука не гасла).
        last_said = max((e["id"] for e in events
                         if e["author"] == v and e["kind"] in active),
                        default=0)
        if h and last_said <= h:
            hands.append((h, v))
    if hands:
        uniq = [v for _, v in sorted(hands, reverse=True)]
        fresh = [v for v in uniq if v in cool]
        if fresh:
            return fresh[:MAX_VOICES_PER_EVENT], "подняли руку"
        if cool:
            # Руку подняли только те, кто и так сейчас говорил. Слово
            # уходит промолчавшему — рука не пропадает, она сработает
            # следующим ходом.
            return _quietest(cool)[:1], "рука у говоривших, слово молчавшему"

    # Кто дольше всех молчал — так перекос лечится механикой, а не
    # напоминаниями (правило 7: на доске Cursor_W 116 карточек Клода
    # против одной у Джемини).
    return _quietest(cool or roster)[:1], "дольше всех молчал"


def _quietest(cands: list[str]) -> list[str]:
    """Кандидаты от самого молчаливого к самому говорливому.

    Никогда не говорившие идут первыми: у них последняя реплика — нулевая.
    """
    last: dict[str, int] = {v: 0 for v in cands}
    for e in read_events():
        # error здесь наравне с репликой: «дольше всех молчал» мерит,
        # кого дольше всех НЕ ВЫЗЫВАЛИ, а не кто дольше всех не давал
        # связного текста. Без этого сломанный канал — вечный фаворит
        # (см. active в pick_voices).
        if e["author"] in last and e["kind"] in ("say", "pass", "verdict",
                                                 "error"):
            last[e["author"]] = e["id"]
    return sorted(cands, key=lambda v: last[v])


def guards(roster: list[str]) -> str | None:
    """Причина, по которой комната должна замолчать и подождать человека.

    Без этих трёх счётчиков хор — вечный двигатель на деньгах Автора.
    """
    ev = read_events()
    # error в счёте наравне с репликой: вызов был, деньги потрачены.
    # Первая редакция передачи слова оставила guards слепым к ошибкам —
    # и замер субагента дал до 18 платных вызовов на одну реплику
    # человека (12 из них error), прежде чем срабатывал потолок.
    # Пинг-понг ниже по-прежнему меряется только say — согласие ошибкой
    # не выражают.
    tail = [e for e in ev if e["kind"] in ("say", "pass", "error")]

    since_human = 0
    for e in reversed(tail):
        if e["author"] == HUMAN:
            break
        since_human += 1
    if since_human >= MAX_TURNS_WITHOUT_HUMAN:
        return (f"{since_human} реплик подряд без человека — "
                f"комната ждёт Автора")

    says = [e for e in tail if e["kind"] == "say"][-PINGPONG_LIMIT - 1:]
    if len(says) > PINGPONG_LIMIT and all(
            AGREE_RE.search(e["text"]) for e in says[-PINGPONG_LIMIT:]):
        return ("подряд идут согласия — это вежливый пинг-понг, "
                "а не разговор")
    return None


def skew_note(roster: list[str]) -> str | None:
    """Перекос по авторам — вслух, в саму ленту."""
    ev = [e for e in read_events() if e["kind"] in ("say", "pass")]
    if len(ev) < 8:
        return None
    counts: dict[str, int] = {}
    for e in ev:
        counts[e["author"]] = counts.get(e["author"], 0) + 1
    top, n = max(counts.items(), key=lambda kv: kv[1])
    if n / len(ev) >= SKEW_WARN_RATIO and top != HUMAN:
        return (f"перекос: {top} — {n} из {len(ev)} реплик "
                f"({n / len(ev):.0%}). Хор вырождается в монолог.")
    return None


def roster() -> list[str]:
    return [v for v in VOICES if available(v)]


