def _grok_cmd(pfile: Path, cont: bool, proj: Path | None) -> list[str]:
    # Команда собирается СТРОКОЙ для `script -qec` — единственное место,
    # где значения проходят через разбор оболочки. Модель и усилие
    # теперь приходят из окружения (то есть из окна), поэтому каждое
    # подставляемое значение — через shlex.quote: окно фильтрует имена
    # своим MODEL_RE, но этот код обязан быть безопасным сам по себе,
    # а не надеяться на фильтр этажом выше.
    flags = "-c " if cont else ""
    cwd = f"--cwd {shlex.quote(str(proj))} " if proj else ""
    model = f"--model {shlex.quote(GROK_MODEL)} " if GROK_MODEL else ""
    return ["script", "-qec",
            f"grok {flags}{cwd}{model}--prompt-file {shlex.quote(str(pfile))} "
            f"--sandbox read-only --no-plan "
            f"--effort {shlex.quote(GROK_EFFORT)}", "/dev/null"]


