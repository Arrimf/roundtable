def vdir(name: str, ch: dict | None = None) -> Path:
    """Свой каталог каждому голосу — не аккуратности ради: у Грока и Кими
    сессия привязана к рабочему каталогу, и в общем cwd они перетрут
    нити друг друга (решение 2 из ЗАМЫСЕЛ.md).

    У голоса с линиями каталог свой У КАЖДОЙ ЛИНИИ по той же причине,
    только острее: линии идут разными ключами, но `-c` выбирает нить по
    каталогу, и в общем cwd вторая линия продолжила бы разговор первой.
    Каталог называет сам канал (`voices/kimi`, `voices/kimi-alt`)."""
    p = VOICEDIR / (ch["dir"] if ch else name)
    p.mkdir(parents=True, exist_ok=True)
    return p


def load_state(name: str, ch: dict | None = None) -> dict:
    """Состояние НИТИ, а не голоса: у линии свой курсор, своя сессия и
    свой счётчик ходов. Запасная линия обычно отстаёт — она и должна
    получить больше дельты, когда её позовут: она этих реплик не видела.
    Слить состояния было бы враньём в обе стороны (правило 8.5)."""
    p = vdir(name, ch) / "state.json"
    if p.is_file():
        try:
            return json.loads(p.read_text(encoding="utf-8"))
        except Exception:                              # noqa: BLE001
            pass
    # ХОЛОДНЫЙ СТАРТ ЗАПАСНОЙ ЛИНИИ. cursor=0 значит «не видел ничего», и
    # первая же реплика утащила бы ей ВЕСЬ архив ленты: замер ревьюера —
    # 197 событий против 47 у основной, 59 635 символов против 8 171
    # (в 7.3 раза). Платит за это Автор, а пользы ноль: обсуждение живёт
    # в последних репликах, а не в архиве. Поэтому новая линия входит с
    # курсором основной — она «пришла к столу сейчас», а не читает
    # стенограмму с начала времён. Если основной ещё нет — начинаем с
    # хвоста ленты (COLD_TAIL событий), а не с нуля.
    if ch is not None and ch.get("name") != "main":
        main_cursor = 0
        try:
            mp = vdir(name) / "state.json"
            if mp.is_file():
                main_cursor = int(json.loads(
                    mp.read_text(encoding="utf-8")).get("cursor") or 0)
        except Exception:                              # noqa: BLE001
            main_cursor = 0
        if not main_cursor:
            ev = read_events()
            main_cursor = max(0, (ev[-1]["id"] - COLD_TAIL) if ev else 0)
        return {"session": None, "cursor": main_cursor, "turns": 0,
                "cold_start": True}
    return {"session": None, "cursor": 0, "turns": 0}


def save_state(name: str, st: dict, ch: dict | None = None) -> None:
    (vdir(name, ch) / "state.json").write_text(
        json.dumps(st, ensure_ascii=False, indent=1), encoding="utf-8")


