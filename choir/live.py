# `flock` берётся на open file description, а не на процесс, поэтому
# ворота разводят и потоки одного процесса (проверено: второй поток
# получает EWOULDBLOCK). Вся очередь — в `first_free_gate`, она же
# выбирает линию.
_WRITE_LOCK = threading.Lock()

DRAND_URL = "https://api.drand.sh/v2/beacons/quicknet/rounds/latest"


def beacon() -> dict:
    """Свежая подпись публичного маяка drand (League of Entropy).

    Тот же маяк, что бросает жребий на ведущего в choir.py: сеть
    независимых организаций каждые 3 секунды выпускает подписанное
    случайное число, проверить которое может кто угодно и когда угодно.
    """
    import urllib.request
    with urllib.request.urlopen(DRAND_URL, timeout=20) as r:
        d = json.loads(r.read().decode())
    if "round" not in d or "signature" not in d:
        raise RuntimeError(f"маяк вернул неожиданный ответ: {str(d)[:200]}")
    return d


def drand_order(names: list[str], sig: str) -> list[str]:
    """Порядок публикации: сортировка по sha256(подпись + ':' + имя).

    Проверяется в одну строку кем угодно, без доверия к дирижёру:
        curl -s https://api.drand.sh/v2/beacons/quicknet/rounds/<round>
        для каждого имени: sha256(подпись + ':' + имя) → сортировать
    """
    return sorted(names, key=lambda n: hashlib.sha256(
        f"{sig}:{n}".encode()).hexdigest())


