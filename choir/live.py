def _gemini_models() -> str:
    """Список моделей для --model: основная плюс запасные, без дублей.

    По запятой режутся ОБЕ переменные: Автор задаёт модель из окна, и
    список там тоже возможен — склеенный целиком он ушёл бы адаптеру
    одним именем «a,b» (нашёл deepseek). Пустой список не отдаём: с
    `--model ""` голос просто падает, а умолчание известно."""
    seen, out = set(), []
    for src in (GEMINI_MODEL, GEMINI_FALLBACK):
        for m in str(src or "").split(","):
            m = m.strip()
            if m and m not in seen:
                seen.add(m)
                out.append(m)
    return ",".join(out) or "gemini-3.7-flash"


