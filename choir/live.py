def per_channel(name: str, make):
    """Промпт для КАЖДОЙ линии голоса заранее.

    Линию выбирают ворота, и узнать её до занятия нельзя: между «занято
    ли?» и «занял» ворота успевают уйти, а промпт зависит от линии — у
    каждой свой курсор и своя нить. Сборка строки не стоит ничего, вызов
    модели стоит всё; поэтому считаем оба варианта и берём тот, чья
    линия досталась. `make(состояние_нити)` строит текст.
    """
    chans = channels_of(name)
    if not chans:
        return make(load_state(name))
    return {c["name"]: make(load_state(name, c)) for c in chans}


