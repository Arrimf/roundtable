def read_events(since: int = 0) -> list[dict]:
    if not LIVE.exists():
        return []
    out = []
    for line in LIVE.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            e = json.loads(line)
        except Exception:                              # noqa: BLE001
            continue
        if e.get("id", 0) > since:
            out.append(e)
    return out


def next_id() -> int:
    ev = read_events()
    return (ev[-1]["id"] + 1) if ev else 1


def post(author: str, kind: str, text: str, **extra) -> dict:
    """Дописать событие. Под ДВУМЯ замками: threading — от нитей этого
    процесса, flock — от других процессов. Второй появился после ревью
    RoundTable (2026-08-25): окно Автора пишет в ту же ленту из своего
    процесса, и `_WRITE_LOCK` его не видит — next_id() двух писателей
    читал один хвост и раздавал один id дважды. Ленту в тот день ломали
    дважды; flock на самом файле подчиняет всех, кто пишет через post().
    """
    with _WRITE_LOCK:
        LIVE.parent.mkdir(parents=True, exist_ok=True)
        LIVE.touch(exist_ok=True)
        with LIVE.open("r+", encoding="utf-8") as _gate:
            fcntl.flock(_gate, fcntl.LOCK_EX)
            try:
                return _post_locked(author, kind, text, extra)
            finally:
                fcntl.flock(_gate, fcntl.LOCK_UN)


def _post_locked(author: str, kind: str, text: str, extra: dict) -> dict:
    """Тело записи под уже взятыми замками (см. post)."""
    e = {"id": next_id(), "ts": _now(), "author": author, "kind": kind,
         "text": text, "schema": SCHEMA, "live": LIVE_VERSION} | extra
    LIVE.parent.mkdir(parents=True, exist_ok=True)
    with LIVE.open("a", encoding="utf-8") as f:
        f.write(json.dumps(e, ensure_ascii=False) + "\n")
    return e


