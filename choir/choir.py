def _debts_open() -> list[dict]:
    """Незакрытые долги: записи `debt` без парной `paid`."""
    if not DEBTS.exists():
        return []
    recs, paid = [], set()
    for line in DEBTS.read_text(encoding="utf-8").splitlines():
        try:
            d = json.loads(line)
        except Exception:                                           # noqa: BLE001
            continue
        if d.get("role") == "paid":
            paid.add((d["round"], d["phase"], d["voice"]))
        elif d.get("role") == "debt":
            recs.append(d)
    return [d for d in recs if (d["round"], d["phase"], d["voice"]) not in paid]


