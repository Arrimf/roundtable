# у стола станет две последовательности фаз — терминальная и оконная, —
# и разойдутся они молча, как расходятся два журнала (устав RoundTable:
# «одна истина — Choir/live.jsonl»). Окно должно уметь ровно одно:
# позвать `choir.py run` и показать, что тот напишет в room.jsonl.
#
# Такт НИЧЕГО не решает сам: он вызывает те же cmd_pick/cmd_expand/
# cmd_ask/cmd_rebut/cmd_summarize, что и человек руками, и добавляет
# только сторожевые условия остановки. Это прямо по правилу 10:
# дирижёр — журналирующий координатор, а не арбитр. Всё, что такт
# решает молча, однажды прочтётся как «стол решил», поэтому каждая
# остановка пишется в журнал причиной и цифрами (правило 4).
# ─────────────────────────────────────────────────────────────────────

# Сколько попыток свода делает такт ВСЕГО, включая ведущего: одна
# ведущему + две запасным по жребию. Каждая попытка — платный вызов
# модели на длинном промпте (все ответы раунда), поэтому «пока
# кто-нибудь не сведёт» здесь неприемлемо: это тот же бесконечный
# ретрай, которым Кими закапывал свою квоту (см. _kimi_quota).
