def _stop_flag(round_id: str) -> Path:
    """Файл-рычаг «останови такт»: ~/.cache/choir/stop-<раунд>.

    Почему файл, а не сигнал процессу. Такт запускают из окна отдельным
    процессом, и «прервать» оттуда сегодня значит убить его — то есть
    потерять ответы текущей слепой фазы: они по правилу 8.5 держатся
    только в памяти дирижёра и на диск до закрытия фазы не попадают
    (см. QUARANTINE). Файл даёт ШТАТНУЮ остановку: начатая фаза
    дописывается до конца и ложится в журнал, следующая не начинается,
    причина называется вслух.

    Имя чистится от разделителей пути: имя раунда приходит и из окна, и
    с рук, а `stop-../../что-нибудь` не должно указывать наружу кэша.
    Для допустимых имён раундов (буквы, цифры, точка, дефис) замена —
    тождественная.
    """
    return QUARANTINE / ("stop-" + re.sub(r"[^\w.-]", "_", round_id))


def _seen_ids(round_id: str) -> set:
    """Снимок id записей раунда — чтобы потом отличить свои от чужих."""
    return {r.get("id") for r in read_round(round_id)}


def _new_answers(round_id: str, seen: set, phases: tuple[str, ...]) -> list[dict]:
    """Ответы, появившиеся в журнале после снимка `seen`.

    Почему через журнал, а не через возвращаемое значение подкоманд:
    cmd_ask/cmd_rebut отдают наружу только код возврата, а такту нужны
    статусы поимённо (кто по квоте, кто замолчал, кто отвечал 3 секунды).
    Менять их сигнатуры ради этого нельзя — это правка поведения
    существующих команд; журнал же и так содержит всё нужное, и такт
    читает его ровно тем же способом, каким прочтёт человек через месяц.
    """
    return [r for r in read_round(round_id)
            if r.get("id") not in seen and r.get("role") == "answer"
            and r.get("phase") in phases]


def _rebuts_arg(s: str) -> int:
    """--rebuts: 0…MAX_REBUT_ROUNDS, и превышение — ОШИБКА, не усечение.

    Правило 12: потолок — три витка, и он не «рекомендация по умолчанию».
    Молча урезать 5 до 3 нельзя: человек читал бы вывод как «прошло пять
    витков, спор сошёлся», а прошло три. Тихое исправление чужой команды
    — это как раз то, что правило 10 запрещает дирижёру.
    """
    try:
        n = int(s)
    except ValueError:
        raise argparse.ArgumentTypeError(f"нужно целое число, а не {s!r}")
    if n < 0 or n > MAX_REBUT_ROUNDS:
        raise argparse.ArgumentTypeError(
            f"витков может быть 0…{MAX_REBUT_ROUNDS} (правило 12: потолок — "
            f"три витка, дальше вежливость моделей бесконечна, токены нет); "
            f"{n} не урезается молча")
    return n


def cmd_run(a: argparse.Namespace) -> int:
    """Полный такт раунда: pick → expand → ask → rebut×N → summarize.

    Коды возврата (их читает окно):
      0 — такт дошёл до свода ИЛИ штатно остановлен Автором (стоп-файл);
      1 — такт остановлен сторожевым условием (пустая слепая фаза,
          каскад, квота, отказ ведущего на затравке, свод не написан);
      2 — ошибка аргументов;
      3 — маяк drand недоступен: жребия нет, такта нет (правило 11).
    """
    seed_path = Path(a.seed)
    if not seed_path.is_file():
        print(f"нет файла вопроса: {seed_path}", file=sys.stderr)
        return 2
    question = seed_path.read_text(encoding="utf-8")
    names = [n.strip() for n in a.voices.split(",")] if a.voices else list(VOICES)
    unknown = [n for n in names if n not in VOICES]
    if unknown:
        print(f"неизвестные голоса: {', '.join(unknown)}", file=sys.stderr)
        return 2
    rebuts = a.rebuts                      # уже проверен _rebuts_arg
    caller = (a.caller or "arr").strip()
    # Лимиты ставим на ВЕСЬ такт, а не только на ask: затравку и свод
    # пишет один голос на длинном промпте, и «маленький таймаут на
    # ревизию» (наказ arr 19.08) должен резать и их — иначе такт с
    # --hard-timeout 300 всё равно висит час на своде.
    global TIMEOUT_OVERRIDE, HARD_TIMEOUT
    if getattr(a, "timeout", None):
        TIMEOUT_OVERRIDE = int(a.timeout)
    if getattr(a, "hard_timeout", None):
        HARD_TIMEOUT = int(a.hard_timeout)

    stop = _stop_flag(a.round)
    stop.parent.mkdir(parents=True, exist_ok=True)
    if stop.exists():
        # Хвост прошлого такта. Не снять его — значит убить новый такт
        # чужой командой на первом же шаге, и человек прочтёт это как
        # поломку. Снятие называется вслух, чтобы «стоп не сработал» не
        # выяснялось задним числом.
        stop.unlink(missing_ok=True)
        print(f"снят стоп-файл прошлого такта: {stop}")

    run_id = uuid.uuid4().hex[:12]
    t0 = time.monotonic()
    # ПЛОМБА ЖУРНАЛА НА ВРЕМЯ ТАКТА. Раунд «право-записи-v1» постановил
    # единогласно: append-only у room.jsonl сегодня — обещание (644, без
    # +a, тот же uid). Такт длится десятки минут и запускает шесть чужих
    # CLI; если за это время прошлое журнала изменится, это надо
    # ЗАМЕТИТЬ — запретить под одним пользователем нечем. Пломба и есть
    # то место, ради которого она писалась: без вызова она была бы
    # свойством без механики, чего сама же и не прощает (нашёл kimi,
    # ревьюя эту правку).
    seal0 = journal_seal((ROOM,))
    plan = f"pick → expand → ask → rebut×{rebuts} → summarize"
    # ЗАПИСЬ О НАЧАЛЕ ТАКТА (правило 8.5: свойство, объявленное полем,
    # обеспечивается механикой). Читающий журнал через месяц обязан
    # видеть, что раунд гнала машина, а не человек вёл его по шагам:
    # иначе «стол прошёл три витка» неотличимо от «человек трижды нажал
    # кнопку, глядя на ответы» — а это разные раунды.
    _append({"id": run_id, "ts": _now(), "round": a.round, "phase": "run",
             "voice": "choir", "role": "autorun", "status": "started",
             "caller": caller, "rebuts": rebuts, "called": names,
             "seed_file": str(seed_path.resolve()), "seed_sha": _sha(question),
             "stop_flag": str(stop), "choir": CHOIR_VERSION, "text": plan})

    done: list[str] = []

    def _ding() -> None:
        """Звонок по окончании такта — «как у микроволновки» (просьба
        Автора 2026-08-25). Такт живёт десятки минут, Автор уходит от
        экрана, и молчаливое завершение он находил случайно.

        CHOIR_NO_DING выставляет окно RoundTable своим тактам: у такта
        из окна звуковой сокет УНАСЛЕДОВАН (spawn передаёт окружение
        целиком), paplay играет и под nohup — первая редакция считала
        иначе и звонила дважды, paplay плюс WebAudio окна (нашёл
        субагент). \a — только когда paplay не сыграл И есть терминал:
        иначе локальный запуск тоже звонил дважды (нашли deepseek и
        grok). Нет звука — нет и ошибки."""
        if os.environ.get("CHOIR_NO_DING"):
            return
        rc = 1
        try:
            rc = subprocess.run(
                ["paplay",
                 "/usr/share/sounds/freedesktop/stereo/complete.oga"],
                capture_output=True, timeout=5).returncode
        except Exception:                              # noqa: BLE001
            pass
        if rc != 0 and sys.stdout.isatty():
            print("\a", end="", flush=True)

    def finish(status: str, reason: str, code: int, **extra) -> int:
        """Запись о завершении такта: какие фазы прошли и где встали."""
        tamper = journal_check(seal0, (ROOM,))
        if tamper:
            # Тревога идёт и в журнал, и на экран: запись о подмене,
            # которую видит только терминал, теряется вместе с окном.
            extra["journal_tamper"] = tamper
            print(f"\n⚠ ЖУРНАЛ ИЗМЕНЁН ЗА ВРЕМЯ ТАКТА: {tamper}",
                  file=sys.stderr)
        el = round(time.monotonic() - t0, 1)
        _append({"id": uuid.uuid4().hex[:12], "ts": _now(), "round": a.round,
                 "phase": "run", "voice": "choir", "role": "autorun",
                 "status": status, "parent": run_id, "caller": caller,
                 "phases_done": done, "reason": reason, "elapsed_s": el,
                 "choir": CHOIR_VERSION,
                 "text": f"такт {status}: {reason}", **extra})
        mark = {"done": "✓", "stopped": "■"}.get(status, "✗")
        print(f"\n{mark} такт «{a.round}» {status} за {el:.0f} с — {reason}")
        print(f"  прошли фазы: {', '.join(done) or 'ни одной'}")
        print(f"  журнал: {ROOM}")
        _ding()
        return code

    def halted_by_author(next_phase: str) -> bool:
        """Проверка стоп-файла ПЕРЕД каждой следующей фазой."""
        if not stop.exists():
            return False
        stop.unlink(missing_ok=True)       # рычаг одноразовый: сработал — снят
        print(f"\n■ найден стоп-файл — фаза {next_phase} не начата")
        return True

    print(f"══ такт «{a.round}»: {plan}")
    print(f"   вопрос: {seed_path}  (sha {_sha(question)})")
    print(f"   голоса: {', '.join(names)}")
    print(f"   прервать штатно:  touch {stop}\n")

    # ── фаза: ЖРЕБИЙ (правило 11) ────────────────────────────────────
    # Fail-closed зашит в cmd_pick: маяк недоступен → код 3 и никакого
    # локального random(). Такт эту строгость не смягчает — иначе он бы
    # тихо вернул назначение ведущего, ради отмены которого жребий и
    # заведён.
    print("── 1. жребий: кто ведёт раунд ──")
    # У раунда МОЖЕТ уже быть ведущий: такт перезапускают после стопа или
    # сбоя. Бросить жребий второй раз значит молча заменить ведущего, чью
    # затравку стол уже читал, — автомат решил бы то, что решает жребий
    # (правило 11). Переброс — только явной командой `pick` (нашёл
    # ревьюер автопрогона).
    was = [r for r in read_round(a.round) if r.get("role") == "lot"]
    if was:
        conductor = was[-1].get("conductor")
        print(f"   у раунда уже есть ведущий: {conductor} "
              f"(жребий не перебрасываю — правило 11; "
              f"нужен другой — сначала `pick`)")
        # Проект жребия и проект такта обязаны совпадать: иначе фазы
        # одного раунда читают разные каталоги (нашли codex, kimi).
        global PROJECT
        lp = was[-1].get("project")
        if lp and PROJECT and str(PROJECT) != lp:
            return finish("failed", f"проект жребия {lp} ≠ --project "
                                    f"{PROJECT}: перебросьте жребий (`pick "
                                    f"--project`) или уберите флаг", 2)
        if lp and not PROJECT:
            lpp = Path(lp)
            if lpp.is_dir():
                PROJECT = lpp
                print(f"   проект раунда (из жребия): {lpp}")
            else:
                return finish("failed", f"проект жребия исчез: {lp}", 2)
        done.append("pick:существующий")
    else:
        if cmd_pick(argparse.Namespace(round=a.round, seed=str(seed_path),
                                       voices=a.voices)) != 0:
            return finish("failed", "маяк drand недоступен — жребия нет, "
                                    "такт не начат (правило 11, fail-closed)",
                          3)
        done.append("pick")
    lots = [r for r in read_round(a.round) if r.get("role") == "lot"]
    conductor = lots[-1].get("conductor") if lots else None
    if not conductor:
        return finish("failed", "жребий не записал ведущего", 1)

    # ── фаза: ЗАТРАВКА (правило 11.5) ────────────────────────────────
    if halted_by_author("expand"):
        return finish("stopped", "остановлен Автором перед фазой expand", 0)
    print(f"\n── 2. затравка: разворачивает {conductor} ──")
    zt = ROOM.parent / f"ЗАТРАВКА-{a.round}.md"
    if cmd_expand(argparse.Namespace(round=a.round, seed=str(seed_path),
                                     by=None, out=str(zt),
                                     effort=a.effort)) != 0 or not zt.is_file():
        # Запасного жребия здесь НЕТ намеренно. Ведущий выбран на весь
        # раунд, и перебросить его на затравке — значит переиграть сам
        # жребий, а это решение стола, не автопрогона. Правило 11
        # разрешает подменять ведущего только на своде.
        return finish("failed",
                      f"ведущий {conductor} не развернул затравку — "
                      f"перебросьте жребий вручную (choir.py pick)", 1)
    done.append("expand")

    # ── фаза: СЛЕПОЙ РАУНД (правило 9) ───────────────────────────────
    if halted_by_author("ask"):
        return finish("stopped", "остановлен Автором перед слепой фазой", 0)
    print(f"\n── 3. слепая фаза: {len(names)} голосов ──")
    seen = _seen_ids(a.round)
    cmd_ask(argparse.Namespace(round=a.round, seed=str(zt), voices=a.voices,
                               out=None, timeout=a.timeout,
                               hard_timeout=a.hard_timeout, effort=a.effort))
    blind = _new_answers(a.round, seen, ("blind",))
    ok = [r for r in blind if r.get("status") == "ok"]
    quota = [r for r in blind if r.get("status") == "quota"]
    done.append("ask")

    # КАСКАДНЫЙ СТОП. Гнать критику по пустой слепой фазе бессмысленно и
    # платно: rebut цитирует ответы, которых нет, а свод сведёт пустоту.
    # Два разных случая называем разными словами — правило 4: «упал —
    # так и записать», и одинаковой записи для «все каналы легли» и «все
    # ответили пусто» быть не должно.
    if not ok:
        fast = bool(blind) and all((r.get("elapsed_s") or 0) < CASCADE_SUSPECT_S
                                   for r in blind)
        why = (f"все {len(blind)} голосов отказали быстрее {CASCADE_SUSPECT_S} с — "
               "похоже на общий сбой инфраструктуры, а не на позицию стола"
               if fast else
               "слепая фаза не дала ни одного ответа — критиковать и сводить нечего")
        return finish("failed", why, 1, cascade=fast,
                      statuses={r["voice"]: r.get("status") for r in blind})
    # КВОТА-СТОП. Повтор при исчерпанной квоте закапывает лимит глубже:
    # у Кими счётчик рос ОТ САМИХ ОТКАЗОВ, ~4 300 токенов на отбитый
    # запрос (см. _kimi_quota). Раунд, где больше половины стола вне
    # квоты, всё равно не раунд — это опрос двоих под видом шестерых
    # (правило 7.5 о перекосе в пользу доступного канала).
    if len(quota) * 2 > len(names):
        return finish("failed",
                      f"{len(quota)} из {len(names)} голосов вне квоты — "
                      "такт остановлен, повтор только закапывает лимит; "
                      f"долги записаны, добрать: choir.py catchup --round {a.round}",
                      1, quota=[r["voice"] for r in quota])
    print(f"\n   слепая фаза: ответили {len(ok)} из {len(names)}")

    # ── фаза: ОТКРЫТАЯ КРИТИКА (правила 9 и 12) ──────────────────────
    for i in range(1, rebuts + 1):
        if halted_by_author(f"rebut {i}/{rebuts}"):
            return finish("stopped",
                          f"остановлен Автором перед витком критики {i}", 0)
        print(f"\n── 4.{i} открытая критика, виток {i} из {rebuts} ──")
        seen = _seen_ids(a.round)
        cmd_rebut(argparse.Namespace(round=a.round, out=None, force=False,
                                     effort=a.effort, focus=a.focus))
        got = _new_answers(a.round, seen,
                           tuple(f"rebut{k}" for k in range(1, 99)))
        done.append(f"rebut{i}")
        if not got:
            # Витка не было: цитировать нечего или все каналы легли.
            # Следующие витки гнать бессмысленно — но слепые ответы
            # есть, и свод по ним состоится.
            print("   виток не состоялся — дальше сразу свод")
            # В журнал ОБЯЗАТЕЛЬНО: иначе «стол сделал один виток»
            # неотличимо от «столько и просили» — молчаливое решение
            # оркестрации прочтётся как решение стола (правила 8.5 и 10).
            _append({"id": uuid.uuid4().hex[:12], "ts": _now(),
                     "round": a.round, "role": "warning",
                     "status": "rebuts_cut", "planned": rebuts, "done": i,
                     "choir": CHOIR_VERSION,
                     "text": f"витки прекращены на {i} из {rebuts}: "
                             f"виток не дал ни одного ответа"})
            break
        q2 = [r for r in got if r.get("status") == "quota"]
        if len(q2) * 2 > len(got):
            print(f"   {len(q2)} из {len(got)} вне квоты — витки прекращены")
            _append({"id": uuid.uuid4().hex[:12], "ts": _now(),
                     "round": a.round, "role": "warning",
                     "status": "rebuts_cut", "planned": rebuts, "done": i,
                     "choir": CHOIR_VERSION,
                     "text": f"витки прекращены на {i} из {rebuts}: "
                             f"{len(q2)} из {len(got)} голосов вне квоты"})
            break

    # ── фаза: СВОД (правило 11: ведущий сводит; отказал — новый жребий)
    if halted_by_author("summarize"):
        return finish("stopped", "остановлен Автором перед сводом", 0)
    card = Path(a.out) if a.out else ROOM.parent / f"СВОД-{a.round}.md"
    answered = sorted({r["voice"] for r in read_round(a.round)
                       if r.get("role") == "answer" and r.get("status") == "ok"})

    # СОСТОЯНИЕ ГЕЙТА НАЗЫВАЕТСЯ ВСЛУХ ПЕРЕД СВОДОМ.
    #
    # Находка kimi при ревизии гейта, и она главная: карточка обещала
    # «валидатор не выпускает финал», а такт писал СВОД, ни разу не
    # спросив gate_state. Гейт был опционален — то есть поле «запечатан»
    # врало ровно так, как запрещает правило 8.5.
    #
    # Почему не жёсткий запрет по умолчанию: гейт введён сегодня, а
    # журнал живёт с августа, и раунд без intake — норма для всего, что
    # было раньше. Запрет сделал бы обход правилом, а обход, ставший
    # привычкой, хуже отсутствия гейта. Поэтому: статус ВСЕГДА виден и в
    # выводе, и в записи, а `--require-seal` превращает его в условие
    # перехода для тех раундов, где стол этого хочет.
    gst = gate_state(a.round)
    gstatus = gate_status(gst)
    if gstatus == "—":
        print(f"\n   гейт решений: раунд {a.round} через intake не "
              f"проходил (choir.py intake --round {a.round} --seed …)")
    else:
        print(f"\n   гейт решений: {gstatus}"
              + (f", вариантов без вердикта: {len(open_options(gst))}"
                 if open_options(gst) else ""))
    if getattr(a, "require_seal", False) and gstatus != "SEALED":
        return finish("blocked",
                      f"свод не написан: гейт решений в состоянии "
                      f"{gstatus}, требовался SEALED (--require-seal). "
                      f"Ответы раунда в журнале, ничего не потеряно",
                      1, gate_status=gstatus,
                      gate_open=[o["id"] for o in open_options(gst)])

    # ЗАПАСНОЙ ЖРЕБИЙ НА СВОДЯЩЕГО. Повод измерен живьём 2026-08-25:
    # ведущий (Джемини) отказал по ключам, и свод переигрывали руками.
    # Правило 11 прямо предусматривает, что ведущий свод пропускает, —
    # оставалось сделать замену проверяемой, а не «Клод назначил».
    # Жребий берётся ОДИН на все попытки и задаёт ПОРЯДОК (idx, idx+1,
    # …), чтобы вторая попытка не требовала второго обращения к маяку:
    # иначе упавший маяк отменял бы уже оплаченный раунд.
    tried: list[dict] = []
    order: list[str] = []
    who: str | None = conductor
    for attempt in range(RUN_SUMMARY_TRIES):
        if attempt and halted_by_author("следующая попытка свода"):
            return finish("stopped", "остановлен Автором на своде", 0,
                          summary_tries=tried)
        print(f"\n── 5. свод (попытка {attempt + 1} из {RUN_SUMMARY_TRIES}) ──")
        rc = cmd_summarize(argparse.Namespace(round=a.round, by=who,
                                              out=str(card), effort=a.effort))
        sums = [r for r in read_round(a.round) if r.get("role") == "summary"]
        st = sums[-1].get("status", "?") if sums else "?"
        tried.append({"voice": who, "status": st})
        if rc == 0:
            done.append("summarize")
            # ПЕРЕПРОВЕРКА. Первая проверка была до свода, а свод идёт
            # минутами: за это время в раунде мог пройти supersede, и
            # финал ушёл бы с полем gate_status=SEALED, которое к моменту
            # записи уже неправда (нашёл codex). Поле пишем то, что
            # верно СЕЙЧАС, и рядом — id той самой печати.
            gst2 = gate_state(a.round)
            gstatus2 = gate_status(gst2)
            if gstatus2 != gstatus:
                print(f"   ⚠ гейт сменил состояние за время свода: "
                      f"{gstatus} → {gstatus2}")
            return finish("done", f"свод написал {who} → {card}", 0,
                          summary_by=who, card=str(card),
                          summary_tries=tried, answered=answered,
                          # Поле пишется ВСЕГДА, даже когда гейт раунд не
                          # видел: «через гейт не проходил» — тоже факт, и
                          # молчание вместо него читалось бы как «прошёл».
                          gate_status=gstatus2,
                          gate_status_before_summary=gstatus,
                          sealed_id=(gst2["sealed"] or {}).get("id"))
        print(f"   {who} не свёл ({st})")
        if not order:
            # Кандидаты — только ответившие ok в ЭТОМ раунде: сводить
            # должен тот, кто в раунде был. Ведущий из списка исключён —
            # он уже отказал.
            cands = [v for v in answered if v != conductor]
            if not cands:
                break
            base = f"{a.round}:summary:{','.join(cands)}"
            q_sha = hashlib.sha256(base.encode()).hexdigest()
            try:
                b = beacon()
            except Exception as e:                              # noqa: BLE001
                # Fail-closed, как в cmd_pick: без маяка выбор никем не
                # проверяем, а в проверяемости весь смысл. Такт честно
                # заканчивается без карточки — назначать сводящего
                # молча дирижёр не вправе (правило 13).
                print(f"   маяк недоступен ({type(e).__name__}) — "
                      "запасного жребия нет", file=sys.stderr)
                break
            mix = hashlib.sha256(f"{b['signature']}:{q_sha}".encode()).hexdigest()
            idx = int(mix, 16) % len(cands)
            order = cands[idx:] + cands[:idx]
            # Роль намеренно НЕ "lot": cmd_expand берёт ведущего как
            # lots[-1]["conductor"], и вторая запись с этой ролью
            # переназначила бы ведущего всего раунда задним числом.
            _append({"id": uuid.uuid4().hex[:12], "ts": _now(), "round": a.round,
                     "phase": "summary", "voice": "choir", "role": "lot_summary",
                     "text": order[0], "candidates": cands, "order": order,
                     "skipped_conductor": conductor, "skipped_status": st,
                     "lot_input": base, "question_sha": q_sha,
                     "drand_round": b["round"], "drand_signature": b["signature"],
                     "mix_sha": mix, "index": idx, "choir": CHOIR_VERSION})
            print(f"   ведущий {conductor} пропускает свод ({st}); "
                  f"новый жребий: {' → '.join(order)}")
            print(f"   проверить: sha256(подпись + ':' + sha256({base!r})) "
                  f"mod {len(cands)} = {idx}  [drand {b['round']}]")
        nxt = [v for v in order if v not in {t["voice"] for t in tried}]
        if not nxt:
            break
        who = nxt[0]

    # Свода нет — и это записывается как факт, а не заминается
    # (правило 4). Ответы раунда в журнале целы; свести можно вручную.
    return finish("failed",
                  "свод не написан: " +
                  ", ".join(f"{t['voice']}={t['status']}" for t in tried) +
                  f"; свести вручную: choir.py summarize --round {a.round} --by <голос>",
                  1, summary_tries=tried, answered=answered)


def _hist_files(name: str, since: float) -> list[Path]:
    """Файлы истории CLI, изменённые после метки времени."""
    h = Path.home()
    pats = {
        "codex":  [(h / ".codex/sessions", "**/rollout-*.jsonl")],
        "grok":   [(h / ".grok/sessions", "**/updates.jsonl")],
        "kimi":   [(h / ".kimi-code/sessions", "**/wire.jsonl")],
        "claude": [(h / ".claude/projects", "**/*.jsonl")],
        # У HTTP-вызова своей истории не бывает — её пишет сам адаптер
        # gemini-http, ради этой самой возможности восстановления.
        # ~/.gemini/tmp оставлен для ответов, полученных ещё через CLI.
        "gemini": [(h / ".gemini/choir-http", "*.jsonl"),
                   (h / ".gemini/tmp", "**/*.json"), (h / ".gemini/tmp", "**/*.jsonl")],
    }.get(name, [])
    out = []
    for root, pat in pats:
        if root.is_dir():
            out += [p for p in root.glob(pat)
                    if p.is_file() and p.stat().st_mtime >= since]
    return sorted(out, key=lambda p: p.stat().st_mtime, reverse=True)


def _extract(name: str, path: Path) -> tuple[str, str]:
    """(текст промпта, текст ответа) из файла истории CLI.

    У каждого CLI своя схема — общих полей нет, поэтому правила явные.
    Ответ Грока приходит чанками, их надо склеивать.
    """
    prompt, chunks, answer = "", [], ""
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip():
            continue
        try:
            d = json.loads(line)
        except Exception:                          # noqa: BLE001
            continue
        if name == "codex":
            p = d.get("payload", {})
            if p.get("type") == "user_message":
                prompt = p.get("message", "") or prompt
            elif p.get("type") == "agent_message":
                answer = p.get("message", "") or answer
        elif name == "grok":
            u = (d.get("params") or {}).get("update") or {}
            kind, txt = u.get("sessionUpdate"), (u.get("content") or {}).get("text", "")
            if kind == "user_message_chunk":
                prompt += txt
            elif kind == "agent_message_chunk":
                chunks.append(txt)
        elif name == "kimi":
            if d.get("type") == "context.append_message":
                m = d.get("message") or d.get("payload") or {}
                role, txt = m.get("role"), m.get("content")
                txt = txt if isinstance(txt, str) else json.dumps(txt, ensure_ascii=False)
                if role == "user":
                    prompt = txt or prompt
                elif role == "assistant":
                    answer = txt or answer
        elif name == "gemini":
            # Формат пишет наш же gemini-http: две строки role/text.
            txt = d.get("text", "")
            if d.get("role") == "user":
                prompt = txt or prompt
            elif d.get("role") == "assistant":
                answer = txt or answer
        elif name == "claude":
            m = d.get("message") or {}
            c = m.get("content")
            txt = "".join(x.get("text", "") for x in c if isinstance(x, dict)) \
                if isinstance(c, list) else (c if isinstance(c, str) else "")
            if d.get("type") == "user":
                prompt = txt or prompt
            elif d.get("type") == "assistant" and txt.strip():
                answer = txt
    return prompt, (answer or "".join(chunks))


def cmd_recover(a: argparse.Namespace) -> int:
    """Достать ответ голоса из истории его CLI после сбоя.

    Вопрос arr: «если в процессе раунда сбой — можно ли вытащить ответ
    потом?» Да: все пять CLI пишут сессии на диск, и ответ там есть,
    даже если дирижёр не дождался (таймаут, разрыв, убитый процесс).
    Ищем по журналу — берём промпт, который голос получил, и находим в
    истории CLI сессию с этим же промптом.

    Восстановленная запись помечается `recovered: true` и своим
    источником: это не то же самое, что ответ, полученный вовремя, и
    в журнале это должно быть видно.
    """
    recs = [r for r in read_round(a.round)
            if r.get("voice") == a.voice and r.get("role") == "answer"]
    if not recs:
        print(f"в раунде {a.round} нет записи от {a.voice}", file=sys.stderr)
        return 1
    bad = [r for r in recs if r.get("status") != "ok"]
    if not bad:
        print(f"{a.voice} уже ответил в этом раунде — восстанавливать нечего")
        return 0
    target = bad[-1]
    ts = datetime.fromisoformat(target["ts"]).timestamp() - 3600
    files = _hist_files(a.voice, ts)
    if not files:
        print(f"история {a.voice} за это время не найдена", file=sys.stderr)
        return 1
    want = target.get("prompt_sha")
    if not want:
        print("в записи нет prompt_sha — сопоставить сессию не с чем; "
              "восстановление отменено", file=sys.stderr)
        return 1
    for p in files:
        prompt, answer = _extract(a.voice, p)
        if not answer.strip():
            continue
        # СТРОГАЯ сверка по sha промпта. Мягкая эвристика здесь опаснее
        # отсутствия восстановления: на первом же прогоне она подставила
        # ответ из соседней сессии («да» из смоук-теста) — то есть тихо
        # испортила бы архив чужой репликой под именем голоса.
        # Сверяем и целиком, и без хвостовых пробелов: журнал считает sha
        # от промпта как есть, а CLI может записать его подрезанным.
        if want not in (_sha(prompt), _sha(prompt.strip()), _sha(prompt + "\n")):
            continue
        rec = dict(target)
        rec |= {"id": uuid.uuid4().hex[:12], "ts": _now(), "status": "ok",
                "text": answer.strip(), "recovered": True,
                "recovered_from": str(p), "recovered_of": target.get("id"),
                "detail": f"восстановлено из истории {a.voice} "
                          f"(исходный статус: {target.get('status')})"}
        r_new = declared_role(answer)
        if r_new:
            rec["role_declared"] = r_new
        _append(rec)
        print(f"восстановлено: {len(answer)} симв. из {p}")
        print(f"исходный статус был «{target.get('status')}» "
              f"({target.get('detail', '')[:60]})")
        return 0
    print(f"в истории {a.voice} ответа на этот промпт нет — "
          "видимо, CLI упал раньше, чем модель ответила", file=sys.stderr)
    return 1


def cmd_probe(a: argparse.Namespace) -> int:
    """Кто сейчас реально отвечает — дешёвым запросом, а не 900-секундным
    ожиданием. До этого выпавший по квоте голос выяснялся только через
    полный hard-timeout: пятнадцать минут тишины на каждого."""
    names = [n.strip() for n in a.voices.split(",")] if a.voices else list(VOICES)
    global TIMEOUT_OVERRIDE, HARD_TIMEOUT
    TIMEOUT_OVERRIDE, HARD_TIMEOUT = 45, int(a.timeout)
    q = "Ответь одним словом: готов"
    live, dead = [], []
    for n in names:
        r = ask_one(n, q, "probe", "probe", None, "probe", use_role=False)
        okay = r["status"] == "ok" and r.get("text", "").strip()
        (live if okay else dead).append(
            n if okay else f"{n} ({r['status']}"
            f"{': ' + r['quota'] if r.get('quota') else ''})")
        print(f"  {'✓' if okay else '✗'} {n:<10} {r['status']:<9} "
              f"{r.get('secs', 0):>5.0f}с  {r.get('quota') or ''}")
    print(f"\nна связи {len(live)} из {len(names)}: {', '.join(live) or '—'}")
    if dead:
        print(f"молчат: {', '.join(dead)}")
    return 0


def cmd_catchup(a: argparse.Namespace) -> int:
    """Добрать долги: задать выпавшим голосам их вопросы задним числом.

    Ответ метится `late=True` и `nonblind=True` — он написан позже и в
    мире, где чужие ответы уже существуют. Слепота задним числом не
    восстанавливается, и делать вид, что восстановилась, нельзя.
    """
    debts = _debts_open()
    if a.round:
        debts = [d for d in debts if d["round"] == a.round]
    if not debts:
        print("долгов нет")
        return 0
    global TIMEOUT_OVERRIDE, HARD_TIMEOUT
    if getattr(a, "hard_timeout", None):
        HARD_TIMEOUT = int(a.hard_timeout)
    by_voice: dict[str, list[dict]] = {}
    for d in debts:
        by_voice.setdefault(d["voice"], []).append(d)
    print(f"долгов: {len(debts)} у {len(by_voice)} голосов")
    paid = 0
    for voice, items in by_voice.items():
        # один пробник на голос: если он всё ещё в квоте — не мучаем его
        # каждым долгом по очереди
        pr = ask_one(voice, "Ответь одним словом: готов", "probe", "probe",
                     None, "probe", use_role=False)
        if pr["status"] != "ok":
            print(f"  {voice}: всё ещё недоступен ({pr['status']}"
                  f"{': ' + pr['quota'] if pr.get('quota') else ''}) — долги ждут")
            continue
        for d in items:
            try:
                seed = Path(d["seed_file"]).read_text(encoding="utf-8")
            except Exception as e:                                  # noqa: BLE001
                print(f"  {voice}/{d['round']}: затравка недоступна ({e})")
                continue
            print(f"  {voice} ← {d['round']} ({d['phase']})", flush=True)
            # Проект — у каждого долга свой раунд (нашёл codex): без
            # этого поздний ответ шёл из Choir/ и без строки о проекте —
            # другой пакет, чем у ответивших вовремя.
            global PROJECT
            PROJECT = _project_of_round(d["round"])
            lp = next((r.get("project") for r in reversed(read_round(d["round"]))
                       if r.get("role") == "lot"), None)
            if lp and PROJECT is None:
                # Проект был, а каталога нет: добор без него — другой
                # пакет, чем у ответивших вовремя. Долг остаётся.
                print(f"    ✗ проект раунда исчез ({lp}) — долг остаётся")
                continue
            rec = ask_one(voice, seed, d["round"], d["phase"], d["parent"],
                          "open")
            rec["late"] = True
            rec["nonblind"] = True
            rec["catchup_of"] = d["id"]
            _append(rec)
            if rec["status"] == "ok":
                _append({"id": uuid.uuid4().hex[:12], "ts": _now(),
                         "round": d["round"], "phase": d["phase"],
                         "voice": voice, "role": "paid", "parent": d["id"]},
                        target=DEBTS)
                paid += 1
                print(f"    ✓ добран ({len(rec.get('text') or '')} симв.)")
            else:
                print(f"    ✗ {rec['status']} — долг остаётся")
    print(f"\nдобрано {paid} из {len(debts)}")
    return 0


# ─────────────────────────────────────────────────────────────────────
# ГЕЙТ ФИКСАЦИИ РЕШЕНИЙ: intake → propose → decision → sealed
#
# Решение стола, раунд `память-v1` (КАРТОЧКА-память-v1.md, 2026-08-24).
# Болезнь, ради которой это написано, измерена, а не предположена: часть
# решений стола некоторое время существовала БЕЗ канонической связи с
# журналом — они были приняты в переписке, а в room.jsonl их не было.
# Найти такое постфактум нельзя: append-only журнал честно хранит всё,
# что в него дописали, и ничего не знает о том, чего не дописали.
# Формулировка стола, принятая единогласно:
#
#     «Append-only без гейта сохраняет записанное, но не обнаруживает
#      незаписанное.»
#
# Отсюда четыре обязательных события и валидатор на выходе:
#
#     intake     вопрос зарегистрирован как ОБЯЗАТЕЛЬСТВО стола;
#     propose    вариант, который стол рассматривает (у варианта есть id);
#     decision   вердикт по варианту: принят | отклонён | ABANDONED;
#     sealed     раунд закрыт — но только если погашены ВСЕ варианты.
#
# ГДЕ БЛОКИРУЕТ. На `seal` КОНКРЕТНОГО раунда — позиция codex, deepseek и
# grok. Дополнительно долги показываются при `pick` (позиция claude и
# kimi), но НЕ блокируют его. Глобальный запрет «раунда N+1, пока не
# закрыт N» (позиция gemini) стол ОТВЕРГ: параллельные раунды на этом
# столе — практика, а не исключение, и общий запрет даёт общий deadlock —
# один зависший раунд запирает стол целиком.
#
# ДВА РАЗНЫХ ДОЛГА, И СМЕШИВАТЬ ИХ НЕЛЬЗЯ (требование стола дословно:
# «Долг ответа отдельного голоса нельзя смешивать с долгом финального
# решения раунда»). Долг ГОЛОСА — голос не ответил, он лежит в
# debts.jsonl и добирается через `catchup`; это отказ канала, а не
# незакрытое решение. Долг РЕШЕНИЯ — вариант без вердикта или раунд с
# intake без печати. Поэтому долг голоса `seal` НЕ блокирует: иначе
# суточная квота Кими навсегда запирала бы фиксацию решения, которое
# стол уже принял. Но и промолчать о нём нельзя — он называется в выводе
# и уходит в запись `sealed` полем `voice_debts`.
#
# ЧЕСТНАЯ ГРАНИЦА ГАРАНТИИ (уточнение codex в карточке). Гейт гарантирует
# полноту ТОЛЬКО относительно зарегистрированных вариантов: вариант, о
# котором никто не сделал `propose`, для валидатора не существует.
# Незаписанное по-прежнему невидимо — гейт лишь сдвигает границу с
# «решение не записано» на «вариант не записан». Это сказано в справке
# каждой команды прямым текстом, чтобы зелёная печать не читалась как
# «стол рассмотрел всё».
#
# ХРАНИЛИЩЕ НЕДОСТУПНО → ПЕРЕХОД НЕ СОСТОЯЛСЯ (правило 8.5: свойство,
# объявленное полем, обязано быть обеспечено механикой, иначе поле врёт).
# Печать, которая не записалась, но напечатала «запечатан», — ровно та
# ложь, против которой весь гейт. Поэтому запись пробуется ДО вывода
# итога, а отказ хранилища возвращает код 3 и говорит об этом вслух.
# ─────────────────────────────────────────────────────────────────────

# Вердикты. «ABANDONED» латиницей намеренно — стол назвал его так в
# карточке, и он не перевод «отклонён»: отклонён значит «рассмотрели и
# отвергли», ABANDONED значит «бросили, не додумав». Разница видна только
# если слова разные.
VERDICTS = ("принят", "отклонён", "ABANDONED")

# Ввод человека нормализуем, но храним канонические слова: «отклонен»
# без ё — не другой вердикт, а другая раскладка.
_VERDICT_ALIAS = {
    "принят": "принят", "принято": "принят", "accepted": "принят",
    "accept": "принят", "+": "принят",
    "отклонён": "отклонён", "отклонен": "отклонён",
    "отклонено": "отклонён", "rejected": "отклонён",
    "reject": "отклонён", "-": "отклонён",
    "abandoned": "ABANDONED", "заброшен": "ABANDONED",
    "abandon": "ABANDONED",
}

GATE_ROLES = ("intake", "propose", "decision", "supersede", "sealed")


def _verdict(raw: str) -> str | None:
    return _VERDICT_ALIAS.get(str(raw).strip().lower()) \
        or (str(raw).strip() if str(raw).strip() in VERDICTS else None)


def _age_str(ts) -> str:
    """Возраст словами. «nan ч назад» в отчёте о долгах — не число, а
    молчание, притворившееся числом: у записи, дописанной руками при
    миграции, `ts` может не быть вовсе, и об этом надо СКАЗАТЬ."""
    h = _age_h(ts)
    return f"{h:>5.1f} ч назад" if h == h else "времени нет"


def _age_h(ts) -> float:
    """Возраст записи в часах.

    Отдельной функцией потому, что `ts` в журналах — строка ISO
    (`_now()`), а старый код в `cmd_debts` вычитал её из `time.time()`
    и падал TypeError на первом же непогашенном долге. Долг, о котором
    нельзя спросить, ничем не отличается от долга, которого нет.
    """
    if isinstance(ts, (int, float)):
        return (time.time() - float(ts)) / 3600
    try:
        d = datetime.fromisoformat(str(ts))
    except Exception:                                           # noqa: BLE001
        return float("nan")
    if d.tzinfo is None:
        d = d.replace(tzinfo=timezone.utc)
    return (datetime.now(timezone.utc) - d).total_seconds() / 3600


# Сколько строк журнала последний read_all не смог разобрать. Не
# исключение и не ноль по умолчанию — ЧИСЛО, которое обязаны назвать
# те, кто заявляет полноту (seal, debts).
SKIPPED_LINES = 0


def read_all() -> list[dict]:
    """Весь журнал, терпимо к битым и старым строкам.

    `read_round` намеренно не трогаем: он падает на битой строке, и это
    его давнее поведение. Но валидатор обязан работать на журнале, где
    записи копились полгода и половина ролей появилась позже него —
    гейт, роняющийся на историческом файле, не гейт.
    """
    global SKIPPED_LINES
    SKIPPED_LINES = 0
    if not ROOM.exists():
        return []
    # Снимок берём под ОБЩИМ замком: пока чужая многочастная запись не
    # дописана, последняя строка выглядит битой, и `seal` отказывал бы по
    # временной гонке, а не по настоящей порче (нашёл codex).
    try:
        with ROOM.open("r", encoding="utf-8") as fh:
            try:
                fcntl.flock(fh.fileno(), fcntl.LOCK_SH)
            except OSError:
                pass
            raw = fh.read()
    except OSError:
        raw = ROOM.read_text(encoding="utf-8")
    out = []
    for line in raw.splitlines():
        if not line.strip():
            continue
        try:
            out.append(json.loads(line))
        except Exception:                                       # noqa: BLE001
            # Молча глотать нечитаемую строку нельзя: печать заявляет
            # полноту ОТНОСИТЕЛЬНО ЖУРНАЛА, а часть журнала при этом не
            # прочитана. Субагент воспроизвёл: обрубленная строка
            # `propose` — и seal выдаёт зелёное «вариантов 2», хотя один
            # из них потерян. Счёт ведём, называет его seal и debts.
            SKIPPED_LINES += 1
    return out


def gate_state(round_id: str, recs: list[dict] | None = None) -> dict:
    """Состояние гейта по раунду, собранное ТОЛЬКО из журнала.

    Отдельного файла состояния нет намеренно — по той же причине, по
    которой его нет у ролей (`current_roles`): второе место, где
    написано, что стол решил, однажды разойдётся с первым, и разойдётся
    молча.

    Порядок событий берётся из порядка строк в файле, а не из `ts`:
    время у нас секундной точности, два события одной секунды в журнале
    упорядочены записью, и только она — правда.
    """
    if recs is None:
        recs = [r for r in read_all() if r.get("round") == round_id]
    st: dict = {"round": round_id, "intake": None, "intakes": [],
                "options": {}, "order": [], "sealed": None,
                "last_seal": None, "reopened": False,
                # что произошло ПОСЛЕ последней печати — по этому списку
                # seal отличает «раунд действительно двинулся» от
                # «печать просто поставили ещё раз»
                "since_seal": [], "orphans": [],
                "participants": [], "has_gate": False}
    seen_voices: list[str] = []
    for rec in recs:
        role = rec.get("role")
        v = rec.get("voice")
        if role == "answer" and v and v not in seen_voices:
            seen_voices.append(v)
        if role not in GATE_ROLES:
            continue
        st["has_gate"] = True
        if role == "sealed":
            st["sealed"] = rec
            st["last_seal"] = rec
            # Флаг сбрасываем ВМЕСТЕ с новой печатью: иначе `reopened`
            # оставался поднятым навсегда, и каждая следующая запись
            # `sealed` несла reopened_before=true, даже когда с прошлой
            # печати не менялось ничего (нашёл субагент-ревьюер).
            st["reopened"] = False
            st["since_seal"] = []
            continue
        # ЛЮБОЙ ход гейта после печати её РАСПЕЧАТЫВАЕТ. Не правкой
        # старой записи (append-only), а тем, что печать перестаёт
        # покрывать журнал: под ней появилось то, чего она не видела.
        # Это и есть наблюдаемый STALE-SEAL.
        #
        # Проверка стоит ВЫШЕ ветки intake, а не ниже. Раньше было ниже,
        # и повторный intake менял обязательство под действующей печатью
        # МОЛЧА: статус оставался SEALED, а карточка ссылалась на первый
        # intake (нашли kimi и grok независимо, проверено запуском).
        if st["sealed"] is not None:
            st["sealed"] = None
            st["reopened"] = True
        st["since_seal"].append(rec)
        if role == "intake":
            st["intakes"].append(rec)
            if st["intake"] is None:
                st["intake"] = rec
            continue
        oid = rec.get("option")
        if not oid:
            # Запись гейта без option — аномалия, а не пустое место:
            # `propose --option ""` печатал «вариант зарегистрирован», а
            # для валидатора варианта не существовало вовсе, и раунд
            # печатался зелёным с «вариантов 0» (нашёл субагент-ревьюер).
            # Вход теперь закрыт в cmd_propose, но исторические строки
            # обязаны быть ВИДНЫ, а не пропущены молча.
            st["orphans"].append({"role": role, "id": rec.get("id"),
                                  "ts": rec.get("ts"), "by": v})
            continue
        o = st["options"].get(oid)
        if o is None:
            o = {"id": oid, "what": "", "what_disputed": None,
                 "by": v, "source": [],
                 "ts": rec.get("ts"), "rec_id": rec.get("id"),
                 "verdict": None, "why": None, "decided_by": None,
                 "decided_id": None, "proposed": False, "history": []}
            st["options"][oid] = o
            st["order"].append(oid)
        if role == "propose":
            if o["proposed"]:
                # Повторный propose тем же id — не перезапись (журнал
                # только дописывается), а факт в истории варианта.
                # `what` в историю ОБЯЗАТЕЛЬНО: без него уточнённое
                # описание исчезало везде, кроме сырого журнала, а CLI
                # обещал «запись добавится в историю варианта» (нашёл
                # субагент-ревьюер). Действующим считаем ПОСЛЕДНЕЕ
                # описание — оно и есть уточнение.
                o["history"].append({"ev": "propose-again", "id": rec.get("id"),
                                     "ts": rec.get("ts"), "by": v,
                                     "what": rec.get("what")
                                     or rec.get("text") or ""})
                new_what = rec.get("what") or rec.get("text")
                if new_what and not o["verdict"]:
                    o["what"] = new_what
                elif new_what and new_what != o["what"]:
                    # ЭТО ДЕФЕКТ, ВНЕСЁННЫЙ ПРЕДЫДУЩЕЙ ПРАВКОЙ. Беря
                    # последнее описание безусловно, я получал печать
                    # решения по тексту, которого никто не решал:
                    # вердикт остаётся от первой редакции, а в карточку
                    # уходит вторая (нашёл codex, ревьюя уже починенный
                    # код). Под действующим вердиктом текст не меняем —
                    # вариант помечается спорным, и seal его назовёт.
                    o["what_disputed"] = new_what
            else:
                o.update({"what": rec.get("what") or rec.get("text") or "",
                          "by": v, "source": list(rec.get("source") or []),
                          "ts": rec.get("ts"), "rec_id": rec.get("id"),
                          "proposed": True})
        elif role == "decision":
            o.update({"verdict": rec.get("verdict"), "why": rec.get("why"),
                      "decided_by": v, "decided_id": rec.get("id")})
            o["history"].append({"ev": "decision", "id": rec.get("id"),
                                 "ts": rec.get("ts"), "by": v,
                                 "verdict": rec.get("verdict"),
                                 "why": rec.get("why")})
        elif role == "supersede":
            o.update({"verdict": rec.get("verdict"), "why": rec.get("why"),
                      "decided_by": v, "decided_id": rec.get("id")})
            o["history"].append({"ev": "supersede", "id": rec.get("id"),
                                 "ts": rec.get("ts"), "by": v,
                                 "replaces": rec.get("replaces"),
                                 "verdict": rec.get("verdict"),
                                 "why": rec.get("why")})
    st["participants"] = seen_voices
    return st


def open_options(st: dict) -> list[dict]:
    """Варианты без вердикта — то, что держит печать."""
    return [st["options"][o] for o in st["order"]
            if not st["options"][o]["verdict"]]


def gate_status(st: dict) -> str:
    """Одно слово о раунде — то самое «наблюдаемое состояние», которого
    стол потребовал для оборванных раундов."""
    if not st["intake"]:
        return "NO-INTAKE" if st["has_gate"] else "—"
    if st["sealed"]:
        # Печать при открытых вариантах — не SEALED. Такое состояние
        # рождается гонкой (кто-то сделал propose между чтением
        # состояния и дозаписью печати) и читалось как закрытый раунд,
        # хотя `debts` тут же показывал у него вариант без вердикта:
        # строка сама себе противоречила (воспроизвёл субагент-ревьюер).
        # Замок в _append сузил окно, но состояние всё равно достижимо —
        # значит статус обязан его называть, а не заглаживать.
        return "SEALED" if not open_options(st) else "STALE-SEAL"
    if st["reopened"]:
        return "STALE-SEAL"
    return "INCOMPLETE"




def _storage_ready(path: Path) -> str | None:
    """Принимает ли журнал дозапись ПРЯМО СЕЙЧАС.

    Проверка перед переходом, а не после: гейт, объявивший решение
    зафиксированным в недоступное хранилище, врёт ровно тем способом,
    против которого он и поставлен (правило 8.5). Сама запись всё равно
    обёрнута try — между проверкой и записью мир может измениться.
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            with path.open("a", encoding="utf-8"):
                pass
        elif not os.access(path.parent, os.W_OK):
            # Проверяем каталог, а НЕ создаём файл: открытие на "a"
            # рождало пустой журнал по первой же опечатке в CHOIR_ROOM,
            # и `debts` честно отвечал «долгов нет» — из пустоты
            # (нашёл субагент-ревьюер).
            return f"каталог {path.parent} недоступен на запись"
    except OSError as e:
        return f"{type(e).__name__}: {e}"
    return None


def _gate_append(rec: dict) -> str | None:
    """Дописать событие гейта. Возврат — текст отказа или None."""
    try:
        _append(rec)
    except OSError as e:
        return f"{type(e).__name__}: {e}"
    return None


def _gate_rec(round_id: str, role: str, by: str, **kw) -> dict:
    """Общий скелет записи гейта: те же поля, что у остальных записей
    комнаты (id/ts/round/phase/voice/role/text), плюс своё."""
    rec = {"id": uuid.uuid4().hex[:12], "ts": _now(), "round": round_id,
           "phase": "gate", "voice": by, "role": role,
           "choir": CHOIR_VERSION}
    rec.update(kw)
    rec.setdefault("text", "")
    return rec


class GateLockError(RuntimeError):
    """Замок гейта взять не удалось — переход не состоялся."""


@contextlib.contextmanager
def gate_lock():
    """Замок на переход гейта: «прочитал состояние → проверил → дописал».

    Замка в `_append` НЕДОСТАТОЧНО, и это проверено, а не предположено:
    пять одновременных `seal` по одному раунду дали ДВЕ записи печати —
    каждый процесс успевал прочитать «не запечатан» до того, как чужая
    запись легла на диск. Замок в _append защищает саму строку, а гейт
    защищать надо ЦЕЛИКОМ, от чтения до дозаписи (нашли kimi, grok и
    субагент-ревьюер независимо; я счёл починенным то, что починено не
    было — ровно тот случай, ради которого правило про чужой глаз).

    Файл замка отдельный, а не сам журнал: flock на журнал уже берёт
    `_append`, и второй flock на тот же файл из того же процесса встал бы
    в собственную очередь.

    Замок недоступен (сетевая ФС без flock, права) — работаем без него и
    ГОВОРИМ об этом: молча ослабший гейт хуже явно отсутствующего.
    """
    lock = ROOM.with_name(ROOM.name + ".gate.lock")
    fh = None
    try:
        lock.parent.mkdir(parents=True, exist_ok=True)
        fh = lock.open("a+")
        fcntl.flock(fh.fileno(), fcntl.LOCK_EX)
    except OSError as e:
        if fh is not None:
            fh.close()
        # Раньше здесь стояло «предупредить и продолжить». Кодекс назвал
        # это тем, чем оно было: атомарность обещана, а при первой же
        # неудаче замка тихо не обеспечена — и два `seal` снова проходят
        # одну проверку. Переход, который нельзя защитить, не делается:
        # код 3 («хранилище не приняло»), а не 0.
        raise GateLockError(str(e)) from e
    try:
        yield
    finally:
        if fh is not None:
            try:
                fcntl.flock(fh.fileno(), fcntl.LOCK_UN)
            except OSError:
                pass
            fh.close()


def under_gate_lock(fn):
    """Команда гейта целиком под замком. Декоратором, а не `with` внутри
    каждой: пять команд — пять мест забыть, а забытый замок не виден до
    первой гонки."""
    def wrapped(a: argparse.Namespace) -> int:
        try:
            with gate_lock():
                return fn(a)
        except GateLockError as e:
            print(f"замок гейта недоступен ({e}). Переход НЕ состоялся: "
                  f"без замка второй такой же вызов прошёл бы ту же "
                  f"проверку и записал бы второе решение.", file=sys.stderr)
            return 3
    wrapped.__name__ = fn.__name__
    wrapped.__doc__ = fn.__doc__
    return wrapped


def _gate_arg(value: str | None, what: str) -> str | None:
    """Проверить обязательный текстовый аргумент гейта.

    `argparse` с `required=True` ловит ОТСУТСТВИЕ флага, а не пустоту его
    значения — и это не педантизм: `intake --round ""` заводил
    обязательство, невидимое в отчётах навсегда (`decision_debts`
    группирует через `if r:`), а `propose --option ""` печатал «вариант
    зарегистрирован», которого для валидатора не существовало. Обе дыры
    воспроизведены запуском (субагент-ревьюер).

    Возврат — текст отказа или None, если аргумент годен.
    """
    v = (value or "").strip()
    if not v:
        return f"{what} не может быть пустым"
    if any(ch in v for ch in "\n\r\t"):
        return f"{what}: перевод строки и табуляция недопустимы"
    if len(v) > 200:
        return f"{what}: слишком длинно ({len(v)} символов, потолок 200)"
    return None


def _check_args(**kw) -> str | None:
    """Первый непрошедший аргумент — его и назвать."""
    for what, value in kw.items():
        bad = _gate_arg(value, what)
        if bad:
            return bad
    return None


