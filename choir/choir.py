# Внутрипроцессного замка здесь БОЛЬШЕ НЕТ (снят 2026-08-26). Стоял
# `threading.Lock`: Кими нельзя звать параллельно самому себе, пока ключ
# один. С двумя ключами этот замок стал вредным — он выдавался по имени
# ГОЛОСА и запер бы обе линии в одну очередь внутри процесса, то есть
# отменил бы весь выигрыш молча, а в журнале это выглядело бы как «Кими
# опять долго думает».
# Ничего при этом не потеряно: `flock` берётся на open file description,
# а не на процесс, — два потока одного процесса, открывшие файл каждый
# своим `os.open`, разводятся так же честно, как два процесса (проверено
# 2026-08-26: второй поток получает EWOULDBLOCK). Очередь целиком в
# `first_free_gate`, и она же выбирает канал.
_VERSION_CACHE: dict[str, str] = {}


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def journal_seal(paths=(ROOM,)) -> list[str]:
    """Пломба журналов: sha256 + размер + inode на момент вызова.

    Раунд `право-записи-v1` единогласно постановил: append-only у
    room.jsonl и live.jsonl сегодня — ОБЕЩАНИЕ. Проверено на живых
    файлах (нашёл grok, перепроверили kimi и claude): права 644,
    атрибута `+a` нет, владелец тот же `arr` — любой процесс под этим
    пользователем перепишет журнал целиком, и молчаливую правку никто
    не заметит.

    `chattr +a` стол рассмотрел и ОТКЛОНИЛ сам: без root он не ставится
    (grok проверил — CapEff пуст), поддельному ДОПИСЫВАНИЮ не мешает
    (codex) и ломает git (claude). Поэтому здесь не запрет, а
    ОБНАРУЖЕНИЕ: пломба, снятая до операции и сверенная после, ловит
    подмену. Слабее запрета — зато работает без прав root и не врёт о
    себе (правило 8.5).
    """
    out = []
    for p in paths:
        try:
            st = p.stat()          # inode ДО чтения: иначе подмена
            data = p.read_bytes()  # между read и stat дала бы ложную
            h = hashlib.sha256(data).hexdigest()[:16]   # тревогу
            out.append(f"{p.name}:{st.st_ino}:{len(data)}:{h}")
        except OSError as e:
            out.append(f"{p.name}:НЕДОСТУПЕН:{type(e).__name__}")
    return out


def journal_check(before: list[str], paths=(ROOM,)) -> str | None:
    """Сверить пломбу. Возврат — текст тревоги или None.

    Ловим ровно то, чего не должно случаться: журнал стал КОРОЧЕ, его
    начало изменилось или файл подменён. Рост в конце — норма, это и
    есть дозапись.

    ПРЕДЕЛ, названный честно: пломба стережёт прошлое НА МОМЕНТ СНЯТИЯ.
    Запись, добавленную после пломбы и стёртую до проверки, она не
    увидит — для этого нужна следующая пломба. Это обнаружение, а не
    запрет: под одним uid запретить нечем (стол проверил `chattr +a` и
    отклонил сам).
    """
    bad = []
    for was, p in zip(before, paths):
        wp = was.split(":")
        if len(wp) != 4:
            # Файл был недоступен В МОМЕНТ СНЯТИЯ: сравнивать не с чем,
            # и молчать об этом нельзя — подмена в промежутке осталась
            # бы незамеченной (нашёл kimi).
            bad.append(f"{wp[0]}: пломба не снималась — сверить нечем")
            continue
        try:
            name, ino, size, head = wp[0], wp[1], int(wp[2]), wp[3]
        except ValueError:
            # Битая строка пломбы не имеет права ронять finish(): такт
            # остался бы вообще без записи о конце (нашёл grok).
            bad.append(f"{wp[0]}: пломба нечитаема — сверить нечем")
            continue
        try:
            with p.open("rb") as fh:
                prefix = fh.read(size)
            st = p.stat()
        except OSError as e:
            bad.append(f"{name}: стал недоступен ({type(e).__name__})")
            continue
        if str(st.st_ino) != ino:
            bad.append(f"{name}: файл ПОДМЕНЁН (inode {ino} → {st.st_ino})")
        elif len(prefix) < size:
            bad.append(f"{name}: журнал УКОРОЧЕН ({size} → {len(prefix)} байт)")
        elif hashlib.sha256(prefix).hexdigest()[:16] != head:
            # Сверяем ПРЕФИКС, а не размер: перезапись файла тем же
            # объёмом размера не меняет, и проверка «стал ли короче»
            # её пропускала — поймано собственным тестом пломбы, до
            # того как она попала в работу.
            bad.append(f"{name}: ПРОШЛОЕ ИЗМЕНЕНО — начало журнала "
                       f"({size} байт) больше не то")
    return "; ".join(bad) or None


def _append(rec: dict, target: Path | None = None) -> None:
    """Дописать строку в журнал. Пишем сразу, а не в конце: прогон могут
    прервать, и уже полученные ответы терять нельзя. Журнал append-only:
    записи не переписываются никогда.

    `target` позволяет писать в карантин вместо комнаты — так слепая фаза
    остаётся слепой физически, а не на честном слове."""
    rec.setdefault("schema", SCHEMA)
    dst = target or ROOM
    dst.parent.mkdir(parents=True, exist_ok=True)
    line = json.dumps(rec, ensure_ascii=False) + "\n"
    # flock, как в live.py post(): в комнату пишут ДВА процесса (choir.py
    # и live.py), и у гейта запись `sealed` с массивом options легко
    # перерастает буфер потока — тогда одна строка уходит несколькими
    # write(). Тиринга на локальной ФС субагент не воспроизвёл (O_APPEND
    # спасает), но замок нужен не столько от тиринга, сколько ради
    # read-check-append у гейта: без него два `seal` печатают раунд
    # дважды, и оба уверены, что первые.
    with dst.open("a", encoding="utf-8") as f:
        try:
            fcntl.flock(f.fileno(), fcntl.LOCK_EX)
        except OSError:
            pass            # нет flock (сетевая ФС) — пишем как раньше
        f.write(line)
        f.flush()


