def cli_version(name: str) -> str:
    """Версия CLI за голосом. Через месяц «grok» будет другим grok'ом —
    без этого поля ответ в архиве теряет привязку к тому, кто отвечал
    (замечание Kimi и Gemini)."""
    if name in _VERSION_CACHE:
        return _VERSION_CACHE[name]
    v = "?"
    try:
        r = subprocess.run(VOICES[name]["version"], capture_output=True,
                           text=True, timeout=30)
        v = (r.stdout or r.stderr or "").strip().splitlines()[0][:60] or "?"
    except Exception:                              # noqa: BLE001
        pass
    _VERSION_CACHE[name] = v
    return v


