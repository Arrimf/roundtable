# ── долги решений ────────────────────────────────────────────────────

def decision_debts() -> list[dict]:
    """Долги РЕШЕНИЙ по всему журналу — не путать с долгами ответов.

    Возвращает по записи на каждый незакрытый факт: вариант без вердикта
    и раунд с intake без действующей печати. Раунды БЕЗ intake сюда не
    попадают вовсе — гейт введён сегодня, а журнал живёт с августа, и
    объявлять полгода истории «долгом» значит утопить настоящие долги в
    шуме (миграцию исторических раундов стол назвал отдельной работой —
    идея kimi в карточке).
    """
    by_round: dict[str, list[dict]] = {}
    for rec in read_all():
        r = rec.get("round")
        if r:
            by_round.setdefault(r, []).append(rec)
    out: list[dict] = []
    for rid, recs in by_round.items():
        st = gate_state(rid, recs)
        if not st["intake"]:
            # Фильтр стоял на intake, а не на has_gate — и раунд, где
            # propose есть, а intake нет, не давал НИ ОДНОГО долга:
            # свежее обязательство пряталось простым отказом от intake
            # (нашли kimi и субагент-ревьюер независимо). Исторические
            # раунды по-прежнему молчат — у них нет и записей гейта.
            if st["has_gate"]:
                out.append({"round": rid,
                            "kind": "варианты вне обязательства (нет intake)",
                            "what": ", ".join(st["order"][:3]) or "—",
                            "ts": (st["options"][st["order"][0]]["ts"]
                                   if st["order"] else None),
                            "status": gate_status(st)})
            continue
        for o in open_options(st):
            out.append({"round": rid, "kind": "вариант без вердикта",
                        # .get, а не индексация: строку intake могут
                        # дописать РУКАМИ при миграции исторических
                        # раундов (принятая идея kimi), и одна такая
                        # строка без ts роняла `debts` трейсбеком,
                        # скрывая заодно ВСЕ остальные долги
                        # (воспроизвёл субагент-ревьюер).
                        "what": o["id"],
                        "ts": o["ts"] or st["intake"].get("ts"),
                        "status": gate_status(st)})
        status = gate_status(st)
        if status in ("INCOMPLETE", "STALE-SEAL"):
            out.append({"round": rid,
                        "kind": ("раунд не запечатан" if status == "INCOMPLETE"
                                 else "печать устарела (был ход после seal)"),
                        "what": "—", "ts": st["intake"].get("ts"),
                        "status": status})
    out.sort(key=lambda d: str(d["ts"] or ""))
    return out


def warn_decision_debts(stream=sys.stderr) -> int:
    """Показать долги решений, НИЧЕГО не блокируя.

    Позиция claude и kimi в карточке: показывать при `pick`. Их же
    предложение блокировать новые входы по просрочке стол не принял —
    порог просрочки остался нерешённым, а гейт с невыбранным порогом
    запирает стол по вкусу того, кто его пишет.
    """
    d = decision_debts()
    if SKIPPED_LINES:
        # Комментарий у SKIPPED_LINES обещал, что счёт называют seal И
        # debts. Debts молчал — то есть обещание в самом коде было ровно
        # таким же необеспеченным полем, какие ловит гейт (нашёл codex).
        print(f"⚠ строк журнала не разобрано: {SKIPPED_LINES} — список "
              f"долгов может быть НЕПОЛОН (choir.py show --check)",
              file=stream)
    if not d:
        return 0
    print(f"⚠ открытых долгов решений: {len(d)} "
          f"(не блокирует жребий, но они есть)", file=stream)
    for x in d[:8]:
        print(f"    {x['round']:<22} {x['kind']:<38} {x['what']}", file=stream)
    if len(d) > 8:
        print(f"    …и ещё {len(d) - 8}; полный список — choir.py debts",
              file=stream)
    print("", file=stream)
    return len(d)


