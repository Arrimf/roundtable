@under_gate_lock
def cmd_intake(a: argparse.Namespace) -> int:
    """Регистрация вопроса как ОБЯЗАТЕЛЬСТВА стола.

    Обязательство рождается ЗДЕСЬ, а не при закрытии раунда (позиции
    claude и codex в карточке). Это и есть ответ на возражение grok:
    искать обязательства по именам файлов `ВОПРОС-*.md` — соглашение об
    именах, а не гарантия; переименованный файл тихо перестаёт быть
    вопросом. Явная запись переименование переживает.
    """
    bad = _check_args(**{"имя раунда": a.round, "кто (--by)": a.by})
    if bad:
        print(bad, file=sys.stderr)
        return 2
    _say_where()
    seed = Path(a.seed)
    try:
        q = seed.read_text(encoding="utf-8")
    except OSError as e:
        print(f"вопрос не читается: {e}", file=sys.stderr)
        return 2
    bad = _storage_ready(ROOM)
    if bad:
        print(f"хранилище недоступно ({bad}).\n"
              "Обязательство НЕ зарегистрировано — переход не состоялся.",
              file=sys.stderr)
        return 3
    st = gate_state(a.round)
    if st["intake"]:
        print(f"у раунда {a.round} уже есть intake от "
              f"{st['intake'].get('ts')} ({st['intake'].get('voice')}).\n"
              "Журнал только дописывается: повторный intake будет ВТОРОЙ "
              "записью, а первая останется. Так и задумано, но знайте.",
              file=sys.stderr)
    rec = _gate_rec(a.round, "intake", a.by,
                    # Скобки не косметика: `a.about or X if q else ""`
                    # разбирается как `(a.about or X) if q else ""`, и при
                    # ПУСТОМ файле вопроса терялся явно заданный --about —
                    # запись уходила с пустым text (нашёл субагент-ревьюер).
                    text=(a.about
                          or (q.strip().splitlines()[0][:200]
                              if q.strip() else "")),
                    about=a.about or "",
                    seed_file=str(seed.resolve()),
                    seed_sha=_sha(q),
                    seed_sha256=hashlib.sha256(q.encode()).hexdigest())
    err = _gate_append(rec)
    if err:
        print(f"запись не прошла ({err}) — обязательство НЕ зарегистрировано.",
              file=sys.stderr)
        return 3
    print(f"intake {a.round}: обязательство зарегистрировано\n"
          f"  запись     {rec['id']}\n"
          f"  вопрос     {rec['seed_file']}\n"
          f"  sha256     {rec['seed_sha256']}\n"
          f"  о чём      {rec['text'] or '—'}\n"
          f"\nтеперь раунд обязан дойти до seal; пока не дошёл — он "
          f"числится INCOMPLETE в choir.py debts")
    return 0


@under_gate_lock
def cmd_propose(a: argparse.Namespace) -> int:
    """Регистрация ВАРИАНТА, который стол рассматривает."""
    bad = _check_args(**{"имя раунда": a.round, "id варианта": a.option,
                         "описание (--what)": a.what, "кто (--by)": a.by})
    if bad:
        print(bad, file=sys.stderr)
        return 2
    _say_where()
    bad = _storage_ready(ROOM)
    if bad:
        print(f"хранилище недоступно ({bad}). Вариант НЕ зарегистрирован.",
              file=sys.stderr)
        return 3
    st = gate_state(a.round)
    if not st["intake"]:
        print(f"⚠ у раунда {a.round} нет intake — вариант запишется, но "
              f"seal откажет, пока обязательство не зарегистрировано",
              file=sys.stderr)
    if a.option in st["options"] and st["options"][a.option]["proposed"]:
        print(f"вариант {a.option} уже зарегистрирован "
              f"({st['options'][a.option]['ts']}). Правки нет — журнал "
              f"только дописывается; запись добавится в историю варианта.",
              file=sys.stderr)
    rec = _gate_rec(a.round, "propose", a.by, option=a.option,
                    what=a.what, text=a.what, source=list(a.source or []))
    err = _gate_append(rec)
    if err:
        print(f"запись не прошла ({err}) — вариант НЕ зарегистрирован.",
              file=sys.stderr)
        return 3
    print(f"propose {a.round}/{a.option}: {a.what}")
    if a.source:
        print(f"  источники: {', '.join(a.source)}")
    print(f"  запись {rec['id']}")
    return 0


@under_gate_lock
def cmd_decision(a: argparse.Namespace) -> int:
    """Вердикт по варианту: принят | отклонён | ABANDONED."""
    bad = _check_args(**{"имя раунда": a.round, "id варианта": a.option,
                         "основание (--why)": a.why, "кто (--by)": a.by})
    if bad:
        print(bad, file=sys.stderr)
        return 2
    _say_where()
    v = _verdict(a.verdict)
    if not v:
        print(f"неизвестный вердикт: {a.verdict}\n"
              f"допустимы: {' | '.join(VERDICTS)}", file=sys.stderr)
        return 2
    bad = _storage_ready(ROOM)
    if bad:
        print(f"хранилище недоступно ({bad}). Вердикт НЕ записан — "
              f"переход не состоялся.", file=sys.stderr)
        return 3
    st = gate_state(a.round)
    o = st["options"].get(a.option)
    if o is None or not o["proposed"]:
        # Отказ, а не молчаливое создание варианта: вердикт по
        # незарегистрированному варианту — это решение без предмета, и
        # в журнале оно выглядело бы как полный разбор.
        known = ", ".join(st["order"]) or "(ни одного)"
        print(f"вариант {a.option} в раунде {a.round} не зарегистрирован.\n"
              f"известные варианты: {known}\n"
              f"сначала: choir.py propose --round {a.round} "
              f"--option {a.option} --what \"…\"", file=sys.stderr)
        return 2
    if o["verdict"]:
        # Дешёвый путь мимо supersede был открыт и ничем не помечен:
        # второй `decision` тем же option молча перебивал действующий
        # вердикт, и в журнале не оставалось ни previous_verdict, ни
        # replaces — то есть ровно то, что докстринга cmd_supersede
        # обещает «никогда» (нашёл субагент-ревьюер, проверено запуском).
        print(f"у варианта {a.option} уже есть вердикт: "
              f"«{o['verdict']}» ({o['decided_by']}, {o['decided_id']}).\n"
              f"Смена решения — отдельное событие, а не второй decision:\n"
              f"  choir.py supersede --round {a.round} "
              f"--replaces {o['decided_id']} --verdict <новый> --why \"…\"",
              file=sys.stderr)
        return 2
    rec = _gate_rec(a.round, "decision", a.by, option=a.option, verdict=v,
                    why=a.why, text=f"{a.option}: {v} — {a.why}",
                    source=list(a.source or []),
                    proposal_id=o["rec_id"], proposed_by=o["by"],
                    proposal_sources=o["source"],
                    intake_id=(st["intake"] or {}).get("id"))
    err = _gate_append(rec)
    if err:
        print(f"запись не прошла ({err}) — вердикт НЕ записан.",
              file=sys.stderr)
        return 3
    print(f"decision {a.round}/{a.option}: {v}\n"
          f"  основание  {a.why}\n"
          f"  вариант от {o['by']} ({o['rec_id']})\n"
          f"  запись     {rec['id']}")
    # Состояние достраиваем в памяти, а не читаем журнал во второй раз
    # ради косметической строки (замечание kimi).
    o["verdict"] = v
    left = [x["id"] for x in open_options(st)]
    print(f"  осталось без вердикта: {', '.join(left) if left else 'ничего'}")
    return 0


@under_gate_lock
def cmd_supersede(a: argparse.Namespace) -> int:
    """Смена уже принятого решения — НОВЫМ событием, никогда правкой.

    `--replaces` принимает и id варианта, и id записи decision: человек
    помнит то, что видит в выводе, а видит он оба. Без `--verdict`
    вариант возвращается в открытые — печать раунда становится
    STALE-SEAL, и это правильно: решение отменено, а нового ещё нет, и
    журнал обязан показывать именно это, а не пустоту.
    """
    bad = _check_args(**{"имя раунда": a.round, "что заменяем (--replaces)":
                         a.replaces, "основание (--why)": a.why,
                         "кто (--by)": a.by})
    if bad:
        print(bad, file=sys.stderr)
        return 2
    _say_where()
    bad = _storage_ready(ROOM)
    if bad:
        print(f"хранилище недоступно ({bad}). Смена решения НЕ записана.",
              file=sys.stderr)
        return 3
    st = gate_state(a.round)
    oid = a.replaces if a.replaces in st["options"] else None
    if oid is None:
        for k, o in st["options"].items():
            if a.replaces in (o["decided_id"], o["rec_id"]) or \
               any(h.get("id") == a.replaces for h in o["history"]):
                oid = k
                break
    if oid is None:
        known = ", ".join(st["order"]) or "(ни одного)"
        print(f"нечего заменять: {a.replaces} не найден в раунде {a.round}.\n"
              f"известные варианты: {known}", file=sys.stderr)
        return 2
    o = st["options"][oid]
    if not o["verdict"]:
        print(f"у варианта {oid} нет действующего вердикта — заменять "
              f"нечего.\n"
              f"  Вердикт выносит decision, а не supersede:\n"
              f"    choir.py decision --round {a.round} --option {oid} "
              f"--verdict <какой> --why \"…\"", file=sys.stderr)
        return 2
    if a.replaces not in (oid, o["decided_id"]) and not a.stale_ok:
        # Раньше подходил ЛЮБОЙ исторический id варианта — старый
        # decision, старый propose, — а заменялся при этом ДЕЙСТВУЮЩИЙ
        # вердикт. Человек целился в одно, попадал в другое, и журнал
        # честно записывал попадание (нашёл codex).
        print(f"{a.replaces} — не действующее решение варианта {oid}.\n"
              f"  сейчас действует: {o['decided_id']} "
              f"(«{o['verdict']}», {o['decided_by']})\n"
              f"  Заменять нужно его: --replaces {o['decided_id']}\n"
              f"  (сознательно заменить по историческому id: --stale-ok)",
              file=sys.stderr)
        return 2
    v = None
    if a.verdict:
        v = _verdict(a.verdict)
        if not v:
            print(f"неизвестный вердикт: {a.verdict}", file=sys.stderr)
            return 2
    rec = _gate_rec(a.round, "supersede", a.by, option=oid,
                    replaces=a.replaces, verdict=v, why=a.why,
                    text=f"{oid}: {o['verdict']} → {v or 'снова открыт'} — {a.why}",
                    previous_verdict=o["verdict"],
                    previous_decision_id=o["decided_id"],
                    proposal_id=o["rec_id"],
                    intake_id=(st["intake"] or {}).get("id"))
    err = _gate_append(rec)
    if err:
        print(f"запись не прошла ({err}) — смена решения НЕ записана.",
              file=sys.stderr)
        return 3
    print(f"supersede {a.round}/{oid}: было "
          f"«{o['verdict'] or 'вердикта нет'}» → "
          f"{'стало «' + v + '»' if v else 'ВАРИАНТ СНОВА ОТКРЫТ'}\n"
          f"  причина  {a.why}\n"
          f"  заменяет {a.replaces}\n"
          f"  запись   {rec['id']}")
    # Тот же приём, что в decision: достраиваем в памяти вместо второго
    # чтения 2.2 МБ ради одной строки вывода.
    o["verdict"] = v
    st2 = st
    st2["reopened"] = st2["sealed"] is not None or st2["reopened"]
    if st2["reopened"]:
        print(f"\n⚠ печать раунда устарела (STALE-SEAL): под ней появился "
              f"ход, которого она не видела. Нужен новый seal.")
    return 0


def _seal_card(st: dict, sealed: dict) -> str:
    """Карточка печати — ПРОИЗВОДНОЕ от журнала, а не второй канон.

    Стол сказал прямо: «Один канон; своды, карточки и реестр — только
    производные». Поэтому файл собирается из room.jsonl и может быть
    выброшен и пересобран без потерь.
    """
    rid = st["round"]
    L = [CARD_MARK, f"# Печать раунда «{rid}»", "",
         f"Запечатал: **{sealed['voice']}**, {sealed['ts']}  ",
         f"Запись печати: `{sealed['id']}` · intake: "
         f"`{(st['intake'] or {}).get('id', '—')}`  ",
         f"Вопрос: `{(st['intake'] or {}).get('seed_file', '—')}` "
         f"sha256 `{(st['intake'] or {}).get('seed_sha256', '—')}`", "",
         "> Карточка — производное от `room.jsonl`. Канон — журнал.", "",
         "## Варианты и вердикты", "",
         "| Вариант | Что | Кем предложен | Вердикт | Основание |",
         "|---|---|---|---|---|"]
    def cell(x) -> str:
        """Ячейка таблицы. Экранируется ВСЁ, включая id варианта: `oid`
        раньше шёл в строку сырым, и `--option 'a|b'` разъезжал таблицу
        лишней колонкой (нашёл субагент-ревьюер)."""
        return str(x if x not in (None, "") else "—").replace(
            "|", "\\|").replace("\n", " ")

    for oid in st["order"]:
        o = st["options"][oid]
        L.append(f"| `{cell(oid)}` | {cell(o['what'])} | {cell(o['by'])} | "
                 f"**{cell(o['verdict'])}** | {cell(o['why'])} |")
    L += ["", "## Провенанс", ""]
    for oid in st["order"]:
        o = st["options"][oid]
        src = ", ".join(o["source"]) if o["source"] else "источники не указаны"
        L.append(f"- `{cell(oid)}` — "
                 + (f"propose `{o['rec_id']}` ({src})" if o["proposed"] else
                    f"**propose ОТСУТСТВУЕТ** — вариант заведён записью "
                    f"`{o['rec_id']}`, это не предложение")
                 + f"; вердикт `{o['decided_id']}` от {o['decided_by']}"
                 + (f"; событий в истории варианта: {len(o['history'])}"
                    if len(o["history"]) > 1 else ""))
    L += ["", "## Кто участвовал", "",
          ", ".join(st["participants"]) or "ответов в раунде нет", ""]
    vd = sealed.get("voice_debts") or []
    L += ["## Долги ответов голосов (печать они НЕ блокируют)", ""]
    if vd:
        for d in vd:
            L.append(f"- {d['voice']} — {d['round']}/{d['phase']} "
                     f"({d.get('status', '?')})")
        L.append("")
        L.append("Долг ответа голоса и долг решения раунда — разные вещи "
                 "(требование стола); печать закрывает второе, не первое.")
    else:
        L.append("нет")
    return "\n".join(L) + "\n"


@under_gate_lock
def cmd_seal(a: argparse.Namespace) -> int:
    """ВАЛИДАТОР И ГЕЙТ: закрыть раунд, если закрывать есть что.

    Коды возврата: 0 запечатан · 1 не готов (с перечислением) ·
    2 аргументы (в том числе от argparse) · 3 хранилище недоступно
    (переход не состоялся). Третий код отделён от первого намеренно:
    «стол не доработал» и «диск не принял запись» — разные события, и
    одинаковый код научил бы вызывающего лечить одно вместо другого
    (правило 4 в его общем виде: отказ канала не есть позиция участника).
    """
    bad = _check_args(**{"имя раунда": a.round, "кто (--by)": a.by})
    if bad:
        print(bad, file=sys.stderr)
        return 2
    _say_where()
    st = gate_state(a.round)
    skipped = SKIPPED_LINES
    # flush: дальше идёт stderr, и без сброса буфера в логе прогона
    # заголовок раунда всплывёт ПОСЛЕ причины отказа.
    print(f"раунд {a.round}: {gate_status(st)}", flush=True)

    if not st["intake"]:
        print(f"\n✗ НЕ ЗАПЕЧАТАН: обязательство не зарегистрировано.\n"
              f"  У раунда нет записи intake — стол не может закрыть то, "
              f"чего не открывал.\n"
              f"  choir.py intake --round {a.round} --seed ВОПРОС.md",
              file=sys.stderr)
        return 1

    if skipped:
        # Печать заявляет полноту ОТНОСИТЕЛЬНО ЖУРНАЛА. Если часть
        # журнала не прочитана, заявлять нечего: молчаливая зелёная
        # печать над потерянным `propose` — воспроизведённый сценарий.
        print(f"\n✗ НЕ ЗАПЕЧАТАН: {skipped} строк(и) журнала не "
              f"разобрано.\n"
              f"  Журнал {ROOM} повреждён — печать по неполной картине "
              f"была бы ложью о полноте.\n"
              f"  Найти битые строки: choir.py show --check",
              file=sys.stderr)
        return 1

    if st["orphans"]:
        print(f"\n✗ НЕ ЗАПЕЧАТАН: записей гейта без id варианта — "
              f"{len(st['orphans'])}.", file=sys.stderr)
        for x in st["orphans"]:
            print(f"    {x['role']:<10} {x['id']}  {x['ts']}  от {x['by']}",
                  file=sys.stderr)
        print("  Такая запись объявляет вариант, которого для валидатора "
              "нет вовсе. Разберите её вручную или закройте раунд "
              "supersede-ом с явным основанием.", file=sys.stderr)
        return 1

    if st["sealed"] and not st["reopened"]:
        # Повторная печать по неизменившемуся раунду возвращала 0 и
        # писала ВТОРУЮ запись `sealed` — два процесса оба уверены, что
        # первые (нашёл grok, проверено запуском: две записи, оба rc=0).
        print(f"\n✗ НЕ ЗАПЕЧАТАН: раунд уже запечатан "
              f"({st['sealed']['id']}, {st['sealed'].get('ts')}, "
              f"{st['sealed'].get('voice')}), и с тех пор в нём ничего "
              f"не менялось.\n"
              f"  Вторая печать не добавила бы факта, а в журнале стояли "
              f"бы две — и через месяц неясно, какая настоящая.\n"
              f"  Изменить решение: choir.py supersede --round {a.round} …",
              file=sys.stderr)
        return 1

    if (st["reopened"] and not st["order"] and a.allow_empty):
        # Выход из тупика, который создала предыдущая правка: раунд без
        # вариантов, запечатанный с --allow-empty, после второго intake
        # становился STALE-SEAL, а погасить STALE требовалось решением —
        # то есть фиктивным вариантом (нашёл codex). Повторное явное
        # --allow-empty и есть здесь решение человека.
        print("\n⚠ печать пустого раунда ЗАНОВО (--allow-empty): под "
              "прошлой печатью появился intake, вариантов по-прежнему нет.",
              file=sys.stderr)
    elif st["reopened"] and not any(
            r.get("role") in ("decision", "supersede")
            for r in st["since_seal"]):
        # STALE-SEAL, снятый повторной печатью без единого нового
        # вердикта: наблюдаемость «печать устарела» пропадала из долгов,
        # хотя суть раунда не двинулась (нашёл grok).
        ev = ", ".join(f"{r.get('role')} {r.get('id')}"
                       for r in st["since_seal"][:5]) or "—"
        print(f"\n✗ НЕ ЗАПЕЧАТАН: печать устарела, но нового решения "
              f"нет.\n"
              f"  После прошлой печати в раунде: {ev}\n"
              f"  Ни одного decision или supersede среди них. Повторная "
              f"печать погасила бы STALE-SEAL, не закрыв того, что его "
              f"вызвало.", file=sys.stderr)
        return 1

    left = open_options(st)
    disputed = [st["options"][o] for o in st["order"]
                if st["options"][o].get("what_disputed")]
    if disputed:
        print(f"\n✗ НЕ ЗАПЕЧАТАН: у вариантов переписано описание ПОСЛЕ "
              f"вердикта — {len(disputed)}:", file=sys.stderr)
        for o in disputed:
            print(f"    {o['id']:<18} решали: «{(o['what'] or '')[:40]}»\n"
                  f"    {'':<18} дописали: «{o['what_disputed'][:40]}»",
                  file=sys.stderr)
        print(f"\n  Печать зафиксировала бы решение по тексту, которого "
              f"никто не решал.\n"
              f"  Либо supersede с новым вердиктом, либо отдельный "
              f"вариант с новым id.", file=sys.stderr)
        return 1
    unproposed = [st["options"][o] for o in st["order"]
                  if not st["options"][o]["proposed"]]
    debts = [d for d in _debts_open() if d["round"] == a.round]

    if left:
        print(f"\n✗ НЕ ЗАПЕЧАТАН: вариантов без вердикта — {len(left)}:",
              file=sys.stderr)
        for o in left:
            print(f"    {o['id']:<18} {(o['what'] or '(без описания)')[:60]}"
                  f"   от {o['by']}", file=sys.stderr)
        print(f"\n  каждому нужен вердикт — принят, отклонён или явный "
              f"ABANDONED:\n"
              f"    choir.py decision --round {a.round} --option "
              f"{left[0]['id']} --verdict ABANDONED --why \"…\"",
              file=sys.stderr)
        if debts:
            print(f"\n  (отдельно: долгов ответов голосов — {len(debts)}; "
                  f"печать они не блокируют)", file=sys.stderr)
        return 1

    if unproposed:
        # Вариант, заведённый записью decision/supersede, а не propose:
        # `what` пуст, `by` — тот, кто выносил вердикт, а в печать уходил
        # proposal_id, указывающий на запись РЕШЕНИЯ и выданный за id
        # предложения. Провенанс врал ровно в том поле, ради которого
        # codex требовал propose(option_id) (нашёл субагент-ревьюер).
        print(f"\n✗ НЕ ЗАПЕЧАТАН: вариантов без propose — "
              f"{len(unproposed)}:", file=sys.stderr)
        for o in unproposed:
            print(f"    {o['id']:<18} заведён записью {o['rec_id']} "
                  f"({o['decided_by'] or '?'}), предложения нет",
                  file=sys.stderr)
        print(f"\n  Вердикт есть, предмета нет. Зарегистрируйте:\n"
              f"    choir.py propose --round {a.round} "
              f"--option {unproposed[0]['id']} --what \"…\" --by <кто>",
              file=sys.stderr)
        return 1

    if not st["order"]:
        # Пустое множество вариантов гасится тривиально, и раньше это
        # давало зелёную печать по одному лишь intake (нашли kimi и grok,
        # проверено запуском: rc=0). Теперь нужен явный флаг — чтобы
        # «раунд закрыт без вариантов» было РЕШЕНИЕМ человека, а не
        # побочным эффектом валидатора.
        if not a.allow_empty:
            print(f"\n✗ НЕ ЗАПЕЧАТАН: у раунда нет ни одного "
                  f"зарегистрированного варианта.\n"
                  f"  {GATE_CAVEAT}.\n"
                  f"  Печать по пустому множеству закрывает раунд, ничего "
                  f"не закрыв. Если так и надо — скажите это вслух:\n"
                  f"    choir.py seal --round {a.round} --allow-empty "
                  f"--by {a.by}", file=sys.stderr)
            return 1
        print("\n⚠ печать по ПУСТОМУ раунду (--allow-empty): вариантов "
              "не записано.\n"
              f"  {GATE_CAVEAT}.", file=sys.stderr)

    bad = _storage_ready(ROOM)
    if bad:
        print(f"\n✗ НЕ ЗАПЕЧАТАН: хранилище недоступно ({bad}).\n"
              f"  Переход не состоялся. Раунд остаётся "
              f"{gate_status(st)} — это видно в choir.py debts.",
              file=sys.stderr)
        return 3

    counts = {v: 0 for v in VERDICTS}
    for oid in st["order"]:
        counts[st["options"][oid]["verdict"]] = \
            counts.get(st["options"][oid]["verdict"], 0) + 1
    options = [{"id": o["id"], "what": o["what"], "by": o["by"],
                "source": o["source"], "verdict": o["verdict"],
                "why": o["why"], "decided_by": o["decided_by"],
                "proposal_id": o["rec_id"], "decision_id": o["decided_id"],
                "events": len(o["history"])}
               for o in (st["options"][x] for x in st["order"])]
    voice_debts = [{"round": d["round"], "phase": d["phase"],
                    "voice": d["voice"], "status": d.get("status", "?"),
                    "debt_id": d["id"]} for d in debts]

    if a.dry_run:
        print(f"\n✓ проверка пройдена (--dry-run: НИЧЕГО не записано)\n"
              f"  вариантов {len(options)}: " +
              ", ".join(f"{k} {v}" for k, v in counts.items() if v))
        if voice_debts:
            print(f"  долги ответов голосов: {len(voice_debts)} — "
                  f"печать не блокируют, но будут названы в записи")
        return 0

    rec = _gate_rec(a.round, "sealed", a.by,
                    text=(f"запечатан: вариантов {len(options)}, " +
                          ", ".join(f"{k} {v}" for k, v in counts.items() if v)
                          + (f"; открытых долгов ответов: {len(voice_debts)}"
                             if voice_debts else "")),
                    intake_id=st["intake"].get("id"),
                    seed_file=st["intake"].get("seed_file"),
                    seed_sha256=st["intake"].get("seed_sha256"),
                    options=options, counts=counts,
                    participants=st["participants"],
                    voice_debts=voice_debts,
                    reopened_before=st["reopened"],
                    empty=bool(a.allow_empty and not st["order"]),
                    since_last_seal=[{"role": r.get("role"),
                                      "id": r.get("id"), "ts": r.get("ts")}
                                     for r in st["since_seal"]],
                    caveat=GATE_CAVEAT)
    err = _gate_append(rec)
    if err:
        print(f"\n✗ НЕ ЗАПЕЧАТАН: запись не прошла ({err}). "
              f"Переход не состоялся.", file=sys.stderr)
        return 3

    print(f"\n✓ ЗАПЕЧАТАН  ({rec['id']})")
    for o in options:
        print(f"    {o['id']:<18} {o['verdict']:<10} {(o['why'] or '')[:56]}")
    print(f"  участвовали: {', '.join(st['participants']) or '—'}")
    if voice_debts:
        # Названы обязательно и отдельно — стол потребовал не смешивать
        # долг ответа голоса с долгом решения раунда.
        print(f"  ⚠ ОСТАЮТСЯ долги ответов голосов ({len(voice_debts)}) — "
              f"это ДРУГОЙ долг, печать его не гасит:")
        for d in voice_debts:
            print(f"      {d['voice']:<10} {d['phase']:<8} {d['status']}")
        print(f"      добрать: choir.py catchup --round {a.round}")
    else:
        print("  долгов ответов голосов нет")
    print(f"  ! {GATE_CAVEAT}")

    if a.out:
        try:
            p = Path(a.out)
            if p.exists():
                head = ""
                try:
                    head = p.read_text(encoding="utf-8")[:200]
                except OSError:
                    pass
                if CARD_MARK not in head and not a.force:
                    print(f"  ⚠ карточка НЕ записана: {p} существует и "
                          f"писана не мной.\n"
                          f"     Печать в журнале есть — файл лишь "
                          f"производное. Перезаписать: --force",
                          file=sys.stderr)
                    return 0
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(_seal_card(st, rec), encoding="utf-8")
            print(f"  карточка (производное): {p}")
        except OSError as e:
            # Карточка — производное; её потеря не отменяет печати,
            # которая уже в каноне. Но и молчать нельзя.
            print(f"  ⚠ карточка не записана ({e}); печать в журнале есть",
                  file=sys.stderr)
    return 0


def cmd_debts(a: argparse.Namespace) -> int:
    """Два РАЗНЫХ долга, показанные раздельно.

    Требование стола дословно: «Долг ответа отдельного голоса нельзя
    смешивать с долгом финального решения раунда». До гейта здесь был
    один список, и это не стилистика: голос, не ответивший по квоте, и
    вариант, по которому стол не вынес вердикта, лечатся разными
    действиями (`catchup` против `decision`) и разными людьми. Общий
    счётчик прятал вторые за первыми.
    """
    voices = _debts_open()
    # Один вызов на оба употребления: второй decision_debts() ниже читал
    # те же 2.2 МБ журнала заново — ровно тот перерасход, который kimi
    # поймал в decision/supersede (перепроход Fable 2026-08-25).
    dec = decision_debts()          # заодно обновляет SKIPPED_LINES
    if SKIPPED_LINES:
        print(f"⚠ строк журнала не разобрано: {SKIPPED_LINES} — списки "
              f"ниже могут быть НЕПОЛНЫ (choir.py show --check)",
              file=sys.stderr)
    print(f"── ДОЛГИ ОТВЕТОВ ГОЛОСОВ ── {len(voices) or 'нет'}")
    for x in sorted(voices, key=lambda z: str(z["ts"])):
        print(f"  {x['round']:<22} {x['phase']:<8} {x['voice']:<10} "
              f"{x.get('status', '?'):<9} {_age_str(x.get('ts'))}")
    if voices:
        print("  добрать: choir.py catchup [--round …]")

    print(f"\n── ДОЛГИ РЕШЕНИЙ ── {len(dec) or 'нет'}")
    for x in dec:
        print(f"  {x['round']:<22} {x['status']:<12} {x['kind']:<40} "
              f"{x['what']:<18} {_age_str(x.get('ts'))}")
    if dec:
        print("  закрыть: choir.py decision … затем choir.py seal --round …")
        print(f"  ! {GATE_CAVEAT}")

    if getattr(a, "strict", False) and dec:
        # Явно запрошенный код возврата для скриптов. По умолчанию 0:
        # `debts` — смотровая команда, и молчаливое превращение её в
        # гейт запирало бы вызывающих, которые её просто печатают.
        return 1
    return 0


