def _dump(out: str | None, results: dict[str, dict], suffix: str) -> None:
    if not out:
        return
    d = Path(out); d.mkdir(parents=True, exist_ok=True)
    for n, rec in results.items():
        if rec["status"] == "ok":
            (d / f"{n}{suffix}.md").write_text(rec["text"], encoding="utf-8")
    print(f"\nответы разложены в {d}/")


def cmd_show(a: argparse.Namespace) -> int:
    if getattr(a, "check", False):
        # Отказ seal по битому журналу отсылает СЮДА, поэтому команда
        # обязана существовать: подсказка, ведущая в никуда, — тот же
        # необеспеченный обещанием текст, против которого гейт и стоит.
        if not ROOM.exists():
            print(f"журнала нет: {ROOM}", file=sys.stderr)
            return 1
        bad = []
        for i, line in enumerate(
                ROOM.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            try:
                json.loads(line)
            except Exception as e:                          # noqa: BLE001
                bad.append((i, str(e)[:60], line[:70]))
        print(f"журнал: {ROOM}")
        if not bad:
            print("все строки разбираются")
            return 0
        print(f"НЕ РАЗБИРАЮТСЯ строк: {len(bad)}")
        for i, why, head in bad:
            print(f"  строка {i}: {why}\n    {head}…")
        print("\nЖурнал только дописывается: битую строку не удаляют, а "
              "дописывают рядом исправленную и говорят об этом вслух.")
        return 1
    recs = read_round(a.round) if a.round else None
    if recs is None:
        if not ROOM.exists():
            print("комната пуста", file=sys.stderr)
            return 1
        recs = [json.loads(l) for l in ROOM.read_text(encoding="utf-8").splitlines() if l.strip()]
    if not recs:
        print(f"раунд {a.round} не найден", file=sys.stderr)
        return 1
    for rec in recs:
        head = (f"── {rec['voice']} [{rec.get('phase', '?')}/"
                f"{rec.get('status', rec['role'])}] {rec['ts']}")
        print(f"\n{head}\n{rec.get('text', '')[:a.chars]}")
    return 0


INBOX = Path(__file__).resolve().parent / "inbox"
INBOX_CAP = 40          # строк на голос; остальное — счётчиком


def _no_files(name: str) -> bool:
    """Голос физически не видит файлов? Спрашиваем ЖИВОЙ live.py, а не
    свою копию списка: вторая копия однажды разойдётся с первой молча —
    дадут Джемини посредника по файлам, и лоток продолжит утверждать
    «кладёт дирижёр» (нашли kimi и codex, оба указали на дубль)."""
    try:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import live                                       # noqa: PLC0415
        return bool((live.VOICES.get(name) or {}).get("no_files"))
    except Exception:                                      # noqa: BLE001
        return name in ("gemini", "deepseek")


def _safe_name(n: str) -> str:
    """Имя файла для терминала. Сырое имя с \n или ESC подделывает
    вывод — можно нарисовать фальшивую строку чужого голоса (нашли
    codex и kimi независимо)."""
    out = "".join(c if c.isprintable() else "?" for c in n)
    return out if out == n else out + "  ⚠имя с непечатным"


def cmd_inbox(a: argparse.Namespace) -> int:
    """Что лежит в лотках голосов.

    ЧЕГО ЗДЕСЬ НЕТ — провенанса. Каталог говорит, КОМУ он предназначен,
    и только: файл мог положить голос, дирижёр, Автор или любой процесс.
    Первая редакция печатала «голос может писать сам» как факт — при
    том, что права записи никому ещё не выдано, а у Клода заявленный
    `acceptEdits` вообще не ограничивает каталог (нашли codex и kimi).
    Настоящий провенанс появится вместе с манифестом дирижёра, куда
    пишутся кто/когда/чем/sha; до тех пор происхождение — неизвестно, и
    так оно и печатается.
    """
    if not INBOX.exists():
        print(f"лотка нет: {INBOX}", file=sys.stderr)
        return 1
    try:
        dirs = sorted(d.name for d in INBOX.iterdir() if d.is_dir())
    except OSError as e:
        print(f"лоток не читается: {e}", file=sys.stderr)
        return 1
    if a.voice and a.voice not in dirs:
        print(f"нет лотка голоса {a.voice}; есть: {', '.join(dirs)}",
              file=sys.stderr)
        return 2
    names = [a.voice] if a.voice else dirs

    print("происхождение файлов НЕ ЗАФИКСИРОВАНО: манифеста пока нет, "
          "каталог говорит лишь адресата.\nправо записи голосам не "
          "выдано — ждёт раунда право-записи-v1.")
    total = 0
    for name in names:
        d = INBOX / name
        rows = []
        try:
            entries = list(os.scandir(d))
        except OSError as e:
            print(f"\n── {name} ── каталог не читается: {e}")
            continue
        for e in entries:
            if e.name == ".gitkeep":
                continue
            try:
                # lstat, а не stat: симлинк наружу (на /etc/passwd) не
                # должен показываться как обычный файл лотка — размер и
                # время брались бы у ЦЕЛИ, то есть у чужого файла.
                st = e.stat(follow_symlinks=False)
            except OSError:
                continue                # исчез между сканом и stat
            if e.is_symlink():
                try:
                    tgt = os.readlink(e.path)
                except OSError:
                    tgt = "?"
                rows.append((st.st_mtime, _safe_name(e.name),
                             f"→ ССЫЛКА на {_safe_name(str(tgt))[:60]}"))
            elif e.is_dir(follow_symlinks=False):
                try:
                    n = sum(1 for _ in os.scandir(e.path))
                except OSError:
                    n = -1
                rows.append((st.st_mtime, _safe_name(e.name) + "/",
                             f"каталог, файлов: {n if n >= 0 else '?'}"))
            elif e.is_file(follow_symlinks=False):
                rows.append((st.st_mtime, _safe_name(e.name),
                             f"{st.st_size} Б"))
        rows.sort(key=lambda r: r[0], reverse=True)
        how = ("файлов не видит вовсе (прямой HTTP) — сам сюда не положит"
               if _no_files(name) else "может получить право записи "
               "(пока не выдано)")
        print(f"\n── {name} ── {len(rows) or 'пусто'}   [{how}]")
        for ts, nm, what in rows[:INBOX_CAP]:
            print(f"    {nm:<44} {what:<24} "
                  f"{time.strftime('%Y-%m-%d %H:%M', time.localtime(ts))}")
        if len(rows) > INBOX_CAP:
            print(f"    …и ещё {len(rows) - INBOX_CAP}")
        total += len(rows)
    print(f"\nвсего в лотке: {total}")
    if total:
        print("перенос в дерево проекта — руками Автора, после ревизии: "
              "автоматики здесь нет намеренно")
    return 0


def cmd_voices(_: argparse.Namespace) -> int:
    print(f"{'голос':<9}{'на связи':<10}{'версия':<22}{'таймаут':>8}"
          f"{'усилие':>9}   особенности")
    for n, v in VOICES.items():
        note = v.get("note", "")
        if v.get("serial"):
            note += "; очередь по организации"
        if v.get("channels"):
            # Каналы называем прямо здесь: «почему Кими иногда отвечает
            # параллельно себе» должно читаться из `voices`, а не из кода.
            note += f"; линии: {describe(v['channels'])}"
        av = available(n)
        print(f"{n:<9}{'да' if av else 'НЕТ':<10}"
              f"{(cli_version(n) if av else '—'):<22}{v['timeout']:>6} с"
              f"{(eff(n) or '—'):>9}   {note}")
    return 0


